def t_rq6(rows) -> str:
    """RQ6: (a) seeded-mutation detection per operator (§8.1, counts pooled across the
    mutation systems); (b) the §8.2 degradation / stopping-rules check per induced mode."""
    ops = ["add_forbidden_dep", "remove_dep", "add_target", "remove_target",
           "rename_target", "merge_targets"]
    acc: dict[str, dict[str, float]] = {}
    mut_systems = set()
    for r in rows:
        if r["axis"] != "RQ6-mut":
            continue
        mut_systems.add(r["system"])
        try:
            d = acc.setdefault(r["technique"], {})
            d[r["metric"]] = d.get(r["metric"], 0) + float(r["value"])
        except (TypeError, ValueError):
            continue

    def _prf(d):
        tp, fn, fp = d.get("tp", 0), d.get("fn", 0), d.get("fp", 0)
        prec = tp / (tp + fp) if tp + fp else None
        rec = tp / (tp + fn) if tp + fn else None
        f1 = 2 * prec * rec / (prec + rec) if prec and rec else \
            (0.0 if (prec is not None and rec is not None) else None)
        return prec, rec, f1

    def _pct(x):
        return f"{100 * x:.1f}" if x is not None else "--"

    body = []
    total: dict[str, float] = {}
    for op in [o for o in ops if o in acc]:
        d = acc[op]
        for k, v in d.items():
            total[k] = total.get(k, 0) + v
        prec, rec, f1 = _prf(d)
        disp = "\\texttt{" + op.replace("_", "\\_") + "}"
        body.append(f"    {disp} & {int(d.get('n', 0))} & {int(d.get('detected', 0))} & "
                    f"{int(d.get('tp', 0))} & "
                    f"{int(d.get('fn', 0))} & {int(d.get('fp', 0))} & "
                    f"{_pct(prec)} & {_pct(rec)} & {_pct(f1)} \\\\")
    prec, rec, f1 = _prf(total)
    body.append("    \\midrule")
    body.append(f"    \\textbf{{overall}} & {int(total.get('n', 0))} & "
                f"{int(total.get('detected', 0))} & "
                f"{int(total.get('tp', 0))} & {int(total.get('fn', 0))} & "
                f"{int(total.get('fp', 0))} & \\textbf{{{_pct(prec)}}} & "
                f"\\textbf{{{_pct(rec)}}} & \\textbf{{{_pct(f1)}}} \\\\")

    # --- (b) degradation modes ---
    deg: dict[str, dict[str, float]] = {}
    deg_adv: dict[str, list[float]] = {}
    for r in rows:
        if r["axis"] != "RQ6-deg":
            continue
        try:
            v = float(r["value"])
        except (TypeError, ValueError):
            continue
        if r["metric"] == "advisory":
            deg_adv.setdefault(r["technique"], []).append(v)
        elif r["metric"] in ("would_be_false", "suppressed", "leaked"):
            d = deg.setdefault(r["technique"], {})
            d[r["metric"]] = d.get(r["metric"], 0) + v
    deg_body = []
    mode_disp = {"disable_l2": "L2 toolchain lost", "starve_l0_10": "10\\% targets starved",
                 "starve_l0_30": "30\\% targets starved (floor)",
                 "lose_l0": "L0 extractor lost"}
    for mode in ("disable_l2", "starve_l0_10", "starve_l0_30", "lose_l0"):
        if mode not in deg:
            continue
        d = deg[mode]
        wb, sup = d.get("would_be_false", 0), d.get("suppressed", 0)
        adv = deg_adv.get(mode, [])
        # the advisory downgrade is the L0-floor mechanism — only the starvation modes
        # exercise it; per-finding reclassification carries the other two
        adv_cell = (f"{int(sum(adv))}/{len(adv)}"
                    if adv and mode.startswith("starve") else "--")
        deg_body.append(f"    {mode_disp[mode]} & {int(wb)} & {int(sup)} & "
                        f"{_pct(sup / wb) if wb else '--'} & {adv_cell} \\\\")

    n_sys = len(mut_systems)
    del deg_body   # block (b) is prose-only in the paper (macros); its rows stay in stats.json
    return (GEN + "\\begin{table}[t]\n  \\centering\n"
            "  \\caption{" + PAPER_RQ["RQ6"] + " seeded-mutation detection per operator, pooled over "
            + str(n_sys) + " systems (first-party L0 scope): Mut.\\ = injected mutations, "
            "Det.\\ = mutations every expected finding of which was reported, TP/FN/FP = "
            "drift-report findings (one per vanished or new target, edge, rename, or "
            "violation, so a removed target yields several).}\n"
            "  \\label{tab:rq6}\n" + FIT
            + "  \\begin{tabular}{@{}l rrrrr rrr@{}}\n    \\toprule\n"
            "    Operator & Mut. & Det. & TP & FN & FP & Prec. & Rec. & F1 \\\\\n    \\midrule\n"
            + "\n".join(body) + "\n    \\bottomrule\n  \\end{tabular}\n\\end{table}\n")


def _rq6_comb_hist(rows):
    """RQ6 (c) a real change AND evidence loss at once (mutate/combined.py): per induced
    mode, pooled over the mutation systems, where every injected finding surfaced; (d) the
    real-history arm (mutate/history.py): consecutive release pairs under frozen rules.
    Returns (n_sys, combined-table body rows, history-table body rows); the two tables are
    emitted by t_rq6_combined / t_rq6_history."""
    comb = [r for r in rows if r["axis"] == "RQ6-comb" and ":" not in r["technique"] and r["projection"] == "combined"]
    hist = [r for r in rows if r["axis"] == "RQ6-hist"]

    def _sum(rs, technique, metric, system=None):
        return int(sum(float(r["value"]) for r in rs if r["technique"] == technique
                       and r["metric"] == metric and (system is None or r["system"] == system)))

    mode_disp = {"starve_l0_10": "10\\% targets starved", "starve_l0_30": "30\\% starved (floor)",
                 "starve_mutated": "mutated targets starved", "lose_l0": "L0 extractor lost"}
    n_sys = len({r["system"] for r in comb})
    cbody = []
    for mode in ("starve_l0_10", "starve_l0_30", "starve_mutated", "lose_l0"):
        if not any(r["technique"] == mode for r in comb):
            continue
        cells = [_sum(comb, mode, m) for m in ("n", "findings", "drift", "gap", "advisory",
                                                 "silent", "fp")]
        silent = f"\\textbf{{{cells[5]}}}" if cells[5] else "0"
        cbody.append(f"    {mode_disp.get(mode, mode)} & {cells[0]} & {cells[1]} & {cells[2]} & "
                     f"{cells[3]} & {cells[4]} & {silent} & {cells[6]} \\\\")

    hbody = []
    pairs = sorted({(r["system"], r["technique"]) for r in hist},
                   key=lambda st: (SYS_ORDER.index(st[0]) if st[0] in SYS_ORDER else 99, st[1]))
    label_cols = ("architectural", "non-architectural", "extraction-noise")
    for s, t in pairs:
        def v(metric):
            return _sum(hist, t, metric, s)
        pending = v("labels_pending") > 0
        # the counts shown are the findings BOTH raters gave the label (aggregate_results
        # emits `label_<lab>_agreed`); one rater's column would hide the disagreements,
        # which the text reports through raw agreement and kappa
        lab = "--" if pending else "/".join(str(v(f"label_{lc}_agreed")) for lc in label_cols)
        a, b = (x.replace("release-", "") for x in t.split("..", 1))   # nopCommerce tag prefix
        hbody.append(f"    {_disp(s)} {a}$\\to${b} & {v('commits_total')} & "
                     f"{v('commits_build_files')} & {v('drift_total')} & "
                     f"{v('coverage_gap_targets') + v('coverage_gap_edges')} & "
                     f"{v('needs_curation_new_b')} & {lab} \\\\")

    return n_sys, cbody, hbody



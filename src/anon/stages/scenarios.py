# DSL emission — consumes the SAME build_dynamic_view result (plan §3.1#3)
# ---------------------------------------------------------------------------

def _emit_dynamic_views(scenarios: list[dict[str, Any]],
                        facts: dict[str, Any],
                        slugs: SlugRegistry) -> tuple[str, list[str], int, int]:
    """Emit all dynamic view blocks, consuming :func:`build_dynamic_view` (no second
    validation path, plan §3.1#3).

    Emits to Structurizr DSL ONLY steps with ``status == "ok"`` AND ``dsl == true``. Every
    other authored step (``unresolved`` / ``unevidenced``, or a runtime-only ``ok``/``dsl:
    false`` step) is emitted as a NUMBERED COMMENT PLACEHOLDER so GUI step N renders as DSL
    step N — the GUI↔DSL step-number correspondence invariant (plan §11). Lines are prefixed
    with the ``order`` number (``N: a -> b``); same-``order`` steps form a shared-N parallel
    band (the explicit shared-step-number form is PRIMARY over the fragile brace block,
    plan §3.1#5).

    Returns ``(dsl_text, emitted_keys, n_skipped_steps, n_runtime_only_steps)`` where
    ``n_skipped_steps`` counts unresolved + unevidenced steps and ``n_runtime_only_steps``
    counts ``ok``/``dsl:false`` (runtime-only) steps across all emitted scenarios.
    """
    lines: list[str] = [_BANNER]
    emitted_keys: list[str] = []
    n_skipped = 0
    n_runtime_only = 0

    for scenario in scenarios:
        view = build_dynamic_view(scenario, facts)
        key = view["scenario"]
        name = view["name"]
        view_steps = view["steps"]

        # A scenario with zero DSL-eligible steps emits no `dynamic{}` block, but its
        # skipped/runtime-only steps are still counted (so the run-report is honest).
        dsl_eligible = [s for s in view_steps if s.get("status") == "ok" and s.get("dsl")]

        # scope resolution: 'system' literal -> the DSL 'system' identifier; a container
        # scope -> its slug ident. An unresolvable scope skips the whole scenario.
        scope = view["scope"]
        if scope.get("value") == "system":
            scope_ident = "system"
        elif scope.get("status") == "ok" and scope.get("container_id"):
            scope_ident = slugs.assign(scope["container_id"])
        else:
            # Unresolvable scope: the WHOLE block is omitted, so EVERY would-be-emitted
            # step is dropped — including the build-backed ok/dsl:true steps that would
            # otherwise have rendered. Count ALL of them as skipped so the run-report
            # never under-reports drops for a bad-scope scenario ("flagged, never
            # silently dropped"). Runtime-only ok steps are tallied separately, as they
            # are everywhere else (they never reach the DSL even with a good scope).
            n_runtime_only += sum(1 for s in view_steps
                                  if s.get("status") == "ok" and not s.get("dsl"))
            n_skipped += sum(1 for s in view_steps
                             if not (s.get("status") == "ok" and not s.get("dsl")))
            continue

        if not dsl_eligible:
            # tally non-DSL steps even when no block is emitted
            n_skipped += sum(1 for s in view_steps if s.get("status") in ("unresolved", "unevidenced"))
            n_runtime_only += sum(1 for s in view_steps
                                  if s.get("status") == "ok" and not s.get("dsl"))
            continue

        lines.append(f'dynamic {scope_ident} {_dsl_str(key)} {_dsl_str(name)} {{')
        for s in view_steps:
            order = s.get("order", s.get("index"))
            status = s.get("status")
            if status == "ok" and s.get("dsl"):
                fi = slugs.assign(s["from"])
                ti = slugs.assign(s["to"])
                # Structurizr's explicit step-number form `N: a -> b "desc"` — same-`order`
                # steps share the number to render as a parallel band (plan §3.1#5; the
                # shared-N prefix is the safer PRIMARY form over the fragile brace block).
                lines.append(f'    {order}: {fi} -> {ti} {_dsl_str(s.get("description", "Uses"))}')
            elif status == "ok" and not s.get("dsl"):
                # runtime-only: a numbered comment placeholder keeps step numbering aligned
                n_runtime_only += 1
                fn = s.get("from_name", s.get("from_raw", ""))
                tn = s.get("to_name", s.get("to_raw", ""))
                lines.append(f'    // {order}: {fn} -> {tn} '
                             '(runtime-only — not in Structurizr model)')
            else:
                # unresolved / unevidenced: a numbered comment placeholder, never silent
                n_skipped += 1
                fr = s.get("from_raw", "")
                tr = s.get("to_raw", "")
                lines.append(f'    // {order}: {fr} -> {tr} '
                             f'(skipped — {status})')
        lines.append("    autolayout lr")
        lines.append("}")
        emitted_keys.append(key)

    return "\n".join(lines) + "\n", emitted_keys, n_skipped, n_runtime_only


def _write_dynamic_views(ws: Workspace, scenarios: list[dict[str, Any]],
                         facts: dict[str, Any]) -> int:
    """Overwrite ``generated/views/dynamic/`` with one §6.9(c) artifact per scenario.

    The directory is machine-owned: stale artifacts for scenarios no longer in
    ``scenarios.yaml`` are removed, so the serve layer can never echo a step list
    against a scenario the architect deleted."""
    out_dir = ws.dynamic_views_dir
    out_dir.mkdir(parents=True, exist_ok=True)
    for old in out_dir.glob("*.json"):
        old.unlink()
    n = 0
    seen: set[str] = set()
    for scenario in scenarios:
        if not scenario.get("key"):
            continue
        view = build_dynamic_view(scenario, facts)
        if view["slug"] in seen:
            # two keys sanitizing to the same slug ("Order Intake" / "order intake")
            # must not silently overwrite each other: disambiguate deterministically
            # by the authored key's hash, declaration order keeps the bare slug.
            import hashlib
            suffix = hashlib.sha256(view["scenario"].encode("utf-8")).hexdigest()[:8]
            view["slug"] = f"{view['slug']}-{suffix}"
        seen.add(view["slug"])
        # Validate the hand-authored view against schema/dynamic-view.schema.json before
        # writing — the candidate path does this, the scenarios.yaml path historically did
        # not, so a hand-authored bad field (e.g. order: 0) could write a schema-invalid
        # artifact that serve echoes unchecked. FAIL-SOFT (advisory discipline): warn and
        # still write so a user's bad scenarios.yaml can never crash `arch run`.
        try:
            validate_dynamic_view(view)
        except jsonschema.ValidationError as exc:
            log.warning(
                "scenario %r produced a schema-invalid dynamic-view/2 artifact "
                "(%s); writing it anyway (advisory) — fix rules/scenarios.yaml.",
                view.get("scenario", view["slug"]), exc.message)
        dump_json(view, out_dir / f"{view['slug']}.json")
        n += 1
    return n



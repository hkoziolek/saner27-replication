def load(results_csv: pathlib.Path) -> list[dict]:
    with results_csv.open(encoding="utf-8") as f:
        return list(csv.DictReader(f))


def pivot(rows, *, axis, metric, projection=None) -> dict[str, dict[str, float]]:
    """(system -> technique -> value) for one axis/metric (optionally one projection)."""
    out: dict[str, dict[str, float]] = {}
    for r in rows:
        if r["axis"] != axis or r["metric"] != metric:
            continue
        if projection is not None and r["projection"] != projection:
            continue
        try:
            out.setdefault(r["system"], {})[r["technique"]] = float(r["value"])
        except (TypeError, ValueError):
            continue
    return out


def pipeline_overlay(rows, base: dict[str, dict[str, float]], metric: str) -> dict[str, dict[str, float]]:
    """Overlay the module-granularity `pipeline` value (the opencv structure-vs-presentation
    override, projection=module-gran) onto an all-common pivot so the headline pipeline number is
    the structural one, not the coarse presentation curation."""
    for s, d in pivot(rows, axis="fidelity", metric=metric, projection="module-gran").items():
        if "pipeline" in d:
            base.setdefault(s, {})["pipeline"] = d["pipeline"]
    return base


# Tier-P rows arrive through the anonymized channel with the A2 rungs but no `fidelity` axis
# (review 2026-09-13: "P-1 has no floor, no propose row"). The no-curation floor IS the A2 `none`
# rung and the propose draft the `propose_all` rung (the same partitions, on the a2-ablation's
# own common projection), so those two cells are filled from A2 wherever the fidelity axis is
# silent. OSS systems always carry the fidelity rows, so their output is byte-identical.
A2_FALLBACK = {"floor": "none", "propose": "propose_all"}


def a2_fallback(rows, base: dict[str, dict[str, float]], metric: str) -> dict[str, dict[str, float]]:
    a2 = pivot(rows, axis="A2", metric=metric, projection="common-a2")
    for s, d in a2.items():
        for key, rung in A2_FALLBACK.items():
            if key not in base.get(s, {}) and rung in d:
                base.setdefault(s, {})[key] = d[rung]
    return base


#: SAR + naïve techniques scored on the pre-registered all-common projection (§6.4). ARC is
#: excluded (topic-based partial coverage, reported on its own subset) as is the LLM baseline.
ALL_COMMON = ("acdc", "wca", "limbo", "dir", "cc")


def _win_count(rows, metric: str, row: str = "pipeline", strict: bool = True) -> str:
    """"k of n" — systems where the candidate row (pipeline / floor / propose) beats every
    all-common classical baseline; STRICT (>) by default, >= with strict=False. Mirrors
    stats.py's `_wins` rule exactly so caption and macros can never disagree (item 5.1)."""
    base = pivot(rows, axis="fidelity", metric=metric, projection="all-common")
    cand = pipeline_overlay(rows, pivot(rows, axis="fidelity", metric=metric), metric) \
        if row == "pipeline" else base
    oss = [s for s in systems_in(rows) if not P_RE.match(s)]
    scored = [s for s in oss
              if cand.get(s, {}).get(row) is not None
              and any(t in base.get(s, {}) for t in ALL_COMMON)]
    wins = sum(1 for s in scored
               if all((cand[s][row] > base[s][t]) if strict else (cand[s][row] >= base[s][t])
                      for t in ALL_COMMON if t in base[s]))
    return f"{wins} of {len(scored)}"


def systems_in(rows) -> list[str]:
    """OSS corpus in canonical order, then any Tier-P codes (sorted) — never interleaved."""
    present = {r["system"] for r in rows}
    return ([s for s in SYS_ORDER if s in present]
            + sorted(s for s in present if P_RE.match(s)))


def _meta(rows) -> dict[str, dict]:
    m = {}
    for r in rows:
        m.setdefault(r["system"], {"language": r["language"], "ref_grade": r["ref_grade"],
                                   "ref_clusters": r["ref_clusters"], "ref_entities": r["ref_entities"]})
    return m


def _fmt(x) -> str:
    return f"{x:.1f}" if isinstance(x, (int, float)) else "--"



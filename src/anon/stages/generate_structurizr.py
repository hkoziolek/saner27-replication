def check_budgets(containers: dict[str, Container]) -> list[str]:
    """Detect over-budget views (advisory; §9.1/§1.1#1/D§7.2): Container view <=25; each
    Component view (any container with materialized components, D§7.1) <=20. Returns the
    names of over-budget views for the run-report / CLI to surface as a warning. This only
    DETECTS — it never splits, trims, hides, or refuses to emit (D§0.1#3)."""
    over: list[str] = []
    if len(containers) > CONTAINER_BUDGET:
        over.append(f"Containers ({len(containers)} > {CONTAINER_BUDGET})")
    for cid in sorted(containers):
        c = containers[cid]
        if c.components and len(c.components) > COMPONENT_BUDGET:
            over.append(f"Component-{c.name} ({len(c.components)} > {COMPONENT_BUDGET})")
    return over


def run(ws: Workspace) -> dict[str, Any]:
    facts = load_json(ws.enriched_facts if ws.enriched_facts.exists() else ws.curated_facts)
    rules = load_mapping_rules(ws.mapping_rules)

    # §0.4#1: the single shared emission-normalized facts projection. `run` reuses the
    # containers / shape / target_to_container it already computes; `scenario_candidates`
    # / `arch scenarios` import `emission_normalized_facts` for the SAME facts shape.
    facts_emitted, containers, shape, n_targets, target_to_container = \
        _emit_projection(facts, rules)
    edges = build_container_edges(facts, target_to_container)
    # D§3.1/D§4: the targets materialized as components (members of multi-target
    # containers) and the component-altitude projection of their edges. Empty under
    # Model Y, where every module target is already a container.
    materialized = {m for c in containers.values() if len(c.members) >= 2 for m in c.members}
    component_edges = build_component_edges(facts, target_to_container, materialized)
    # D§4 (namespace-tier gap): the INTERIOR edges of a Model-Y module-container (or a D§5
    # expand promotion) — the `…/component:<ns>` namespace->namespace symbol_use edges the
    # Roslyn helper emits. Scoped to components actually materialized in the model so an
    # excluded/aggregated namespace never leaves a dangling edge. Disjoint key space from
    # component_edges (component ids vs target/container ids), so the two merge cleanly.
    emitted_components = {comp.cid for c in containers.values() for comp in c.components}
    namespace_edges = build_namespace_edges(facts, emitted_components)
    # both component-altitude edge dicts share one fragment + the disconnected-leaf
    # accounting; their key spaces are disjoint, so the merge can't collide.
    all_component_edges = {**component_edges, **namespace_edges}

    # element ids that carry at least one edge at EITHER altitude (for the disconnected-
    # leaf exemptions above): an edgeless element is an evidence-based leaf, not a slip.
    connected = ({eid for edge in edges for eid in edge}
                 | {eid for edge in all_component_edges for eid in edge})

    slugs = SlugRegistry()
    ws.components_dsl.parent.mkdir(parents=True, exist_ok=True)
    ws.components_dsl.write_text(emit_components_dsl(containers, slugs, connected),
                                 encoding="utf-8", newline="")
    ws.relationships_dsl.write_text(emit_relationships_dsl(edges, slugs, all_component_edges),
                                    encoding="utf-8", newline="")

    # `facts_emitted` (the §0.4#1 projection) was computed above by `_emit_projection`;
    # the downstream view stages bind elements via each target's emitted `container_id`.

    # P7 view families (§9.3/§9.4): deployment/runtime + dynamic. Run AFTER components so the
    # populated slug registry resolves containerInstance/scenario-step identifiers to the SAME
    # idents used above; run BEFORE the scaffolds so the unconditional !includes in
    # workspace.dsl/views.dsl always point at existing (banner-only when empty) files.
    deploy_res = generate_deployment.run(ws, facts_emitted, slugs)
    dyn_res = scenarios.run(ws, facts_emitted, slugs)
    # Advisory scenario candidates (dynamic-view plan §8): in the `arch run` advisory pass
    # Source B (runtime) runs by DEFAULT; Source C (graph-walk) is OFF by default (opt-in via
    # `arch scenarios --source graph-walk`, §6); Source A is deferred and F (llm) is opt-in
    # only (§4/§7). All reuse the SAME emission-normalized `facts_emitted` so a candidate
    # validates identically when promoted (no inbox bait-and-switch, §0.4#1).
    # Advisory — never fail the run (the §8 advisory-pass discipline).
    try:
        scenario_candidates.run(ws, facts_emitted)   # default sources=["runtime"] — B only
    except Exception:  # pragma: no cover - advisory, never breaks generate
        logging.getLogger("anon.generate_structurizr").warning(
            "scenario-candidate generation failed (advisory; skipped)", exc_info=True)
    # canonical/diagnostic views compiled from view-intents.yaml (§6.1); banner-only by
    # default so the unconditional views.dsl !include always resolves (opt-in/additive).
    view_intent_warnings = _emit_view_intents(ws, facts_emitted)

    # Machine-owned documentation + decisions (§9): regenerated every run, attached via the
    # scaffold's !docs/!adrs so the software-system documentation/decisions inspections pass.
    container_summaries = sorted((c.name, _container_description(c)) for c in containers.values())
    try:
        from . import drift_report
        l0_pct: float | None = round(drift_report._coverage_l0(facts) * 100, 1)
    except Exception:  # pragma: no cover - docs coverage is best-effort
        l0_pct = None
    generate_docs.run(ws, facts_emitted, container_summaries, len(edges), l0_pct=l0_pct)

    system_name = ws.repo.name or "System"
    _scaffold_workspace_dsl(ws, system_name)
    # D§7.1: auto-draw a Component view for EVERY container with >=1 materialized component
    # (Model X: multi-target containers; Model Y: module-containers with an L2 tier; plus
    # D§5 promotions). Identifiers come from the slug registry used above, so the view's
    # `component <ident>` matches the model. A container with NO components gets no view —
    # an empty Component view trips the `views.view.empty` inspection and shows nothing.
    component_views = [(slugs.assign(c.cid), c.name)
                       for c in containers.values() if c.components]
    _scaffold_views_dsl(ws, component_views)


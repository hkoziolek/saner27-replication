def run(ws: Workspace, facts: dict[str, Any], slugs: SlugRegistry) -> dict[str, Any]:
    """Emit ``ws.dynamic_dsl`` from ``ws.scenarios_yaml`` + emission-normalized *facts*.

    Parameters
    ----------
    ws:
        Resolved workspace paths (plan §12).
    facts:
        Emission-normalized fact model (``facts_emitted`` — see
        :func:`generate_structurizr.emission_normalized_facts`).  Each target carries the
        EMITTED ``container_id`` / ``container_name``; ``relationships[]`` carry
        ``source``/``target`` build-target ids; ``deployment.edges`` carry the runtime facet.
    slugs:
        A :class:`SlugRegistry` already populated with all container identifiers so that
        ``slugs.assign(container_id)`` returns the same identifier used in
        ``generated-components.dsl`` and ``generated-relationships.dsl``.

    Returns
    -------
    dict with keys:
        ``scenarios``          — number of dynamic view blocks emitted
        ``views``              — list of scenario keys emitted
        ``skipped_steps``      — number of unresolved/unevidenced steps (flagged in JSON)
        ``runtime_only_steps`` — number of ok/dsl:false steps (valid in JSON, not in DSL)
        ``dynamic_artifacts``  — number of §6.9(c) JSON artifacts written
    """
    ws.dynamic_dsl.parent.mkdir(parents=True, exist_ok=True)

    data = load_yaml(ws.scenarios_yaml)
    scenarios = (data.get("scenarios") or []) if data else []

    if not scenarios:
        # Write a banner-only comment — still valid inside a views {} block. Still
        # sweep generated/views/dynamic/ so a deleted scenarios.yaml leaves no stale
        # §6.9(c) artifact behind for the serve layer to echo.
        ws.dynamic_dsl.write_text(_BANNER, encoding="utf-8", newline="")
        if ws.dynamic_views_dir.exists():
            for old in ws.dynamic_views_dir.glob("*.json"):
                old.unlink()
        return {"scenarios": 0, "views": [], "skipped_steps": 0,
                "runtime_only_steps": 0, "dynamic_artifacts": 0}

    dsl, emitted_keys, n_skipped, n_runtime_only = _emit_dynamic_views(scenarios, facts, slugs)
    ws.dynamic_dsl.write_text(dsl, encoding="utf-8", newline="")
    n_artifacts = _write_dynamic_views(ws, scenarios, facts)

    return {
        "scenarios": len(emitted_keys),
        "views": emitted_keys,
        "skipped_steps": n_skipped,
        "runtime_only_steps": n_runtime_only,
        "dynamic_artifacts": n_artifacts,
    }

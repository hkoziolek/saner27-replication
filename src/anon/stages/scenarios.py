"""Stage 7 — dynamic (behavioral) view generation from hand-authored scenarios (plan §9.4).

Reads ``rules/scenarios.yaml`` (hand-owned, architect-curated) and emits
``generated/generated-dynamic.dsl`` — a set of Structurizr ``dynamic`` view blocks that
sequence EXISTING container relationships — plus, per scenario, the engine §6.9(c)
evidence-validated step-list artifact ``generated/views/dynamic/<scenario>.json`` that
the GUI's sequence strip renders verbatim (``GET /model/dynamic/<scenario>``).

Design principles (§9.4 / engine §6.9c):
  - **Behavior is ordering over evidenced structure (principle #3)**: a dynamic view CANNOT
    invent an edge.  Every step is validated against the curated container graph (BUILD) OR
    the runtime deployment facet (dynamic-view plan §0.3); invalid steps are SKIPPED in the
    DSL and **FLAGGED (never silently dropped) in the JSON** — call order is never invented,
    and an unevidenced step is a first-class answer.
  - **Build vs runtime evidence (dynamic-view plan §0.3/§3.1)**: a step is ``ok`` if its
    ``(from,to)`` is in the build container-edge set OR the runtime ``calls`` edge set. The
    ``evidence_layer`` (``build``/``runtime``) is stamped per step (build wins ties — the
    stronger structural layer). A build-backed step is ``dsl: true`` (Structurizr can draw
    it); a runtime-only step is ``dsl: false`` (no static relationship exists to reference)
    but stays ``ok`` and visible in Anon's JSON/GUI view (plan §0.4#3).
  - **One validator (plan §3.1#3)**: :func:`build_dynamic_view` is the single validation
    result for BOTH the JSON artifact and the DSL emission — :func:`_emit_dynamic_views`
    consumes it rather than re-validating. The GUI↔DSL **step-number correspondence is an
    invariant** (plan §11): a ``dsl:false`` / flagged step is emitted as a NUMBERED DSL
    COMMENT placeholder so GUI step N is always DSL step N.
  - **Always emit the file**: ``generated-dynamic.dsl`` is unconditionally ``!include``d
    by the views scaffold, so the file must exist and be valid inside a ``views {}`` block
    even when no scenarios are configured (banner-only comment in that case).
  - **Deterministic / byte-identical**: steps emit in declaration order (scenarios are
    ordered by the architect); identifiers come from the stable :class:`SlugRegistry`;
    the JSON artifacts carry ``derived_from_hash`` and go through :func:`jsonio.dump_json`.
"""

def _rq9_systems(rows) -> list[str]:
    present = {r["system"] for r in rows if r["axis"] == "RQ9"}
    return [s for s in SYS_ORDER if s in present] + sorted(present - set(SYS_ORDER))


def _rq9_val(rows, s, tech, metric, projection, *, prefix=False):
    if tech is None:
        return None
    for r in rows:
        if r["system"] != s or r["axis"] != "RQ9" or r["metric"] != metric \
                or r["projection"] != projection:
            continue
        if (r["technique"].startswith(tech) if prefix else r["technique"] == tech):
            try:
                return float(r["value"])
            except (TypeError, ValueError):
                return None
    return None


# RQ9: the pre-registered (first) curator per system — mirrors stats.RQ9_PRIMARY_CURATOR so
# the table's "blind curator" row and the macros can never name different people; a further
# curator (the variance arm, response plan 1.5b) gets its own indented row.
RQ9_PRIMARY_CURATOR = {"eshop": "R-A", "squidex": "R-C"}


def _rq9_curators(rows, s) -> tuple[str | None, list[str]]:
    """(technique name of the primary curator, codes of the further curators)."""
    codes = sorted({r["technique"].split(":", 1)[1] for r in rows
                    if r["system"] == s and r["axis"] == "RQ9"
                    and r["technique"].startswith("curator:")})
    plain = any(r["system"] == s and r["axis"] == "RQ9" and r["technique"] == "curator"
                for r in rows)
    primary = (RQ9_PRIMARY_CURATOR.get(s) if RQ9_PRIMARY_CURATOR.get(s) in codes
               else (codes[0] if codes else None))
    tech = f"curator:{primary}" if primary else ("curator" if plain else None)
    return tech, [c for c in codes if c != primary]



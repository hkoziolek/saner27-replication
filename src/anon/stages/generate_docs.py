def _container_metrics(members: list[dict[str, Any]]) -> dict[str, Any]:
    """Sum the metrics/1 per-language rows over the container's members at render time —
    container totals are never stored twice (plan §3.1). Honest absence when no member
    carries source metrics (e.g. an external/package container, or a pre-1.3 artifact)."""
    langs: dict[str, dict[str, int]] = {}
    todo = 0
    engine = None
    for t in members:
        m = t.get("metrics") or {}
        for row in m.get("by_language") or []:
            agg = langs.setdefault(row.get("language", "?"),
                                   {"files": 0, "blank": 0, "comment": 0, "code": 0})
            for k in ("files", "blank", "comment", "code"):
                agg[k] += row.get(k, 0) or 0
        todo += m.get("todo_count", 0) or 0
        engine = engine or m.get("engine")
    if not langs:
        return {"available": False, "reason": "no source metrics extracted",
                "engine": None, "total": None, "todo_count": 0, "by_language": []}
    by_language = [{"language": lang, **vals} for lang, vals in sorted(langs.items())]
    total = {k: sum(r[k] for r in by_language)
             for k in ("files", "blank", "comment", "code")}
    return {"available": True, "engine": engine, "total": total,
            "todo_count": todo, "by_language": by_language}


def _container_technology(members: list[dict[str, Any]]) -> dict[str, Any]:
    """The §6.1 technology fingerprint: DIRECT package refs stamped on member targets
    (survives curation's drop_external). Capped — a manual, not a lockfile dump."""
    pkgs = sorted({p for t in members for p in (t.get("package_refs") or []) if p})
    return {"packages": pkgs[:_TECH_CAP], "packages_total": len(pkgs)}


def _tests_index(facts: dict[str, Any]) -> tuple[set[str], dict[str, set[str]]]:
    """``(test_target_ids, target_id -> test ids that depend on it)`` — pure L0 (§6.3).

    Computed from the EXTRACTED facts when the caller can supply them (see
    :func:`build_datasheets` ``tests_facts``): the common curation pattern *excludes*
    test projects from the model, which would otherwise empty this signal exactly where
    it matters."""
    test_ids = {t["id"] for t in facts.get("targets", []) or []
                if t.get("id") and _is_test_target(t)}
    tested_by: dict[str, set[str]] = {}
    for r in facts.get("relationships", []) or []:
        if r.get("source") in test_ids and r.get("target"):
            tested_by.setdefault(r["target"], set()).add(r["source"])
    return test_ids, tested_by


def _tests_block(member_ids: list[str], test_ids: set[str],
                 tested_by: dict[str, set[str]]) -> dict[str, Any]:
    refs = sorted({src for m in member_ids for src in tested_by.get(m, set())})
    with_tests = sum(1 for m in member_ids if tested_by.get(m))
    return {"test_targets": refs[:_TEST_CAP], "test_targets_total": len(refs),
            "members_with_tests": with_tests,
            "members": len(member_ids),
            "note": "adjacency proxy from the build graph (a test target that "
                    "references the member) — NOT coverage"}


def _risk_echo(risk_report: dict[str, Any] | None, accept_hashes: set[str],
               cid: str) -> dict[str, Any]:
    """ECHO of risk-report.json — the datasheet never recomputes a risk number (§0.4).
    A report computed from different facts is refused as stale, never half-trusted.
    *accept_hashes* holds the hash of every facts tier currently on disk (enriched /
    curated / extracted): `arch risk` reads the curated tier while the datasheets read
    the enriched one, and within one run those are the same model."""
    if not risk_report:
        return {"available": False, "reason": "no risk-report.json — run `arch risk`"}
    if risk_report.get("derived_from_hash") not in accept_hashes:
        return {"available": False,
                "reason": "risk-report.json was computed from different facts — re-run"}
    mine = [f for f in risk_report.get("findings", []) or []
            if cid in (f.get("elements") or [])]
    kinds = sorted({f.get("kind", "?") for f in mine})
    echo: dict[str, Any] = {"available": True,
                            "in_cycle": "cycle" in kinds, "hub": "hub" in kinds,
                            "finding_kinds": kinds,
                            "instability_I": None, "abstractness_A": None,
                            "distance_D": None}
    for f in mine:
        si = f.get("severity_inputs") or {}
        if f.get("kind") == "main-sequence":
            echo["instability_I"] = si.get("instability_I")
            echo["abstractness_A"] = si.get("abstractness_A")
            echo["distance_D"] = f.get("severity")
        elif f.get("kind") == "hub" and echo["instability_I"] is None:
            echo["instability_I"] = si.get("instability_I")
    return echo


def _footprint(measurements: dict[str, Any] | None, member_ids: set[str],
               facts_hash: str) -> dict[str, Any]:
    """Join the Class-V measurements sidecar (plan §5) — timestamped by design, never
    part of any hash; absence is the normal case, staleness is a checkable join."""
    if not measurements:
        return {"available": False,
                "reason": "no measurements.json — run `arch measure` after a build"}
    rows = [r for r in measurements.get("targets", []) or []
            if r.get("id") in member_ids and r.get("found")]
    stale = measurements.get("derived_from_hash") != facts_hash
    if not rows:
        return {"available": False, "stale": stale,
                "reason": "no build artifacts found for this container's members"}
    return {"available": True,
            "size_bytes": sum(r.get("size_bytes", 0) or 0 for r in rows),
            "artifacts": len(rows),
            "measured_at": measurements.get("measured_at"),
            "commit": measurements.get("commit"),
            "stale": stale}


def _cite_universe(facts: dict[str, Any], containers) -> set[str]:
    """Every id a narrative key point may cite: element ids, container ids, and both
    raw `rel:` ids and bare `source->target` edge keys (target- and container-level)."""
    ids: set[str] = {cid for cid in containers}
    for t in facts.get("targets", []) or []:
        if t.get("id"):
            ids.add(t["id"])
        # ADR cites (informative-llm-narratives §2.3): the `adr:<id>` tags adr.run stamped on
        # targets are first-class citable ids, so a decision key point resolves.
        for tag in (t.get("tags") or []):
            if isinstance(tag, str) and tag.startswith("adr:"):
                ids.add(tag)
    t2c = {m: c.cid for c in containers.values() for m in c.members}
    for r in facts.get("relationships", []) or []:
        s, t = r.get("source"), r.get("target")
        if not s or not t:
            continue
        if r.get("id"):
            ids.add(r["id"])
        ids.add(f"{s}->{t}")
        cs, ct = t2c.get(s), t2c.get(t)
        if cs and ct:
            ids.add(f"{cs}->{ct}")
    return ids


def _norm_key_points(raw: Any) -> list[dict[str, Any]]:
    """Normalize override/LLM key points to ``[{text, cites[]}]`` (≤5, plan §4.2)."""
    out = []
    for kp in (raw or [])[:5]:
        if isinstance(kp, str):
            out.append({"text": kp, "cites": []})
        elif isinstance(kp, dict) and kp.get("text"):
            cites = [str(c) for c in (kp.get("cites") or []) if c]
            out.append({"text": str(kp["text"]), "cites": cites})
    return out


def _narrative_block(cid: str, overrides: dict[str, Any] | None,
                     proposed: dict[str, Any] | None, facts_hash: str,
                     cite_universe: set[str]) -> dict[str, Any]:
    """The Class-N narrative (plan §4): human override (hand tier, wins forever) >
    LLM proposal carried in the enriched facts > honest absence. A human override is
    never machine-rejected — unresolvable citations become a `stale_citations` warning,
    not a hard fail (§4.4)."""
    ov = ((overrides or {}).get("narratives") or {}).get(cid)
    if isinstance(ov, dict) and (ov.get("abstract_md") or ov.get("key_points")):
        kps = _norm_key_points(ov.get("key_points"))
        bad = sorted({c for kp in kps for c in kp["cites"] if c not in cite_universe})
        return {"source": "human", "abstract_md": str(ov.get("abstract_md") or ""),
                "key_points": kps, "model_id": None, "derived_from_hash": None,
                "stale": False, "stale_citations": bad, "reason": ""}
    rec = (proposed or {}).get(cid)
    if isinstance(rec, dict) and rec.get("error"):
        return {"source": "none", "abstract_md": "", "key_points": [], "model_id": None,
                "derived_from_hash": None, "stale": False, "stale_citations": [],
                "reason": f"llm-narrative-failed: {rec['error']}"}
    if isinstance(rec, dict) and rec.get("abstract_md"):
        return {"source": "llm", "abstract_md": rec["abstract_md"],
                "key_points": _norm_key_points(rec.get("key_points")),
                "model_id": rec.get("model_id"),
                "derived_from_hash": rec.get("derived_from_hash"),
                "stale": rec.get("derived_from_hash") != facts_hash,
                # informative-llm-narratives §4/§3: surface the band + method for the GUI
                # char-meter and the "agentic" provenance chip (advisory; default omitted).
                "size_band": rec.get("size_band"),
                "method": rec.get("method", "deterministic"),
                "stale_citations": [], "reason": ""}
    return {"source": "none", "abstract_md": "", "key_points": [], "model_id": None,
            "derived_from_hash": None, "stale": False, "stale_citations": [],
            "reason": "no LLM narrative on this run and no hand-written override "
                      "(rules/datasheet-overrides.yaml)"}


_OVERRIDES_HEADER = (
    "# rules/datasheet-overrides.yaml — hand-owned (datasheet-enrichment plan §4.4).\n"
    "# Per-container narrative overrides: they WIN over any LLM proposal, survive\n"
    "# every run, and are never machine-rejected (an unresolvable citation renders\n"
    "# as a warning). Accepting a GUI/LLM proposal copies it here — from then on it\n"
    "# is yours. NOTE: this file is rewritten whole on GUI accept (comments above\n"
    "# this header are not preserved).\n")


def accept_narrative(ws: Workspace, container_id: str, *,
                     abstract_md: str | None = None,
                     key_points: list[dict[str, Any]] | None = None) -> dict[str, Any]:
    """Accept a narrative into the hand-owned overrides file (plan §4.4 / §8): the
    GUI's one-click "accept LLM proposal" (no body → copy the current proposal from
    the enriched facts) or an edited human narrative (body supplied). Returns
    ``{"new_text", "accepted"}`` for the caller to write through its reviewed-write
    path; raises ``KeyError`` (no such proposal) / ``ValueError`` (no propose run)."""
    import yaml as _yaml
    if abstract_md is None:
        if not ws.enriched_facts.exists():
            raise ValueError("no enriched facts — run with --llm-propose first")
        enriched = load_json(ws.enriched_facts)
        # The proposal may live at any altitude: container, component (target), or the
        # single system record (informative-llm-narratives §6.2/§6.3 — same accept path).
        rec = (enriched.get("containers_narrative") or {}).get(container_id) \
            or (enriched.get("components_narrative") or {}).get(container_id)
        sysrec = enriched.get("system_narrative") or {}
        if not rec and sysrec.get("element_id") == container_id:
            rec = sysrec
        if not isinstance(rec, dict) or not rec.get("abstract_md"):
            raise KeyError(container_id)
        abstract_md = rec["abstract_md"]
        key_points = rec.get("key_points") or []
    existing = load_yaml(ws.datasheet_overrides)
    narratives = existing.setdefault("narratives", {})
    narratives[container_id] = {
        "abstract_md": abstract_md,
        "key_points": [{"text": kp["text"], "cites": list(kp["cites"])}
                       for kp in _norm_key_points(key_points)],
    }
    body = _yaml.safe_dump(existing, sort_keys=True, allow_unicode=True,
                           default_flow_style=False)
    return {"new_text": _OVERRIDES_HEADER + body, "accepted": container_id}


def reset_narrative(ws: Workspace, container_id: str) -> dict[str, Any]:
    """Reset to the LLM proposal (informative-llm-narratives §6.1): remove the hand-owned
    override for *container_id* so the element falls back to its LLM proposal (or honest
    absence). Returns ``{"new_text", "accepted"}``; raises ``KeyError`` when there is no
    override to remove."""
    import yaml as _yaml
    existing = load_yaml(ws.datasheet_overrides)
    narratives = existing.get("narratives") or {}
    if container_id not in narratives:
        raise KeyError(container_id)
    del narratives[container_id]
    if not narratives:
        existing.pop("narratives", None)
    body = _yaml.safe_dump(existing, sort_keys=True, allow_unicode=True,
                           default_flow_style=False)
    return {"new_text": _OVERRIDES_HEADER + body, "accepted": container_id}


def git_vitals(repo, facts: dict[str, Any], containers) -> tuple[dict[str, Any] | None, str | None]:
    """Per-container git vitals (plan §6.4), CONDITIONAL on committed history exactly
    like risk's churn detector: the window is anchored to the HEAD commit's date (never
    wall-clock), authors are a COUNT (names never leave git — an egress/privacy hazard
    with no architectural value). Returns ``(per_cid, degraded_reason)``; out-of-tree /
    no-history is the normal absent answer, not an error."""
    from .risk import CHURN_WINDOW_DAYS, _git
    import datetime as _dt
    inside = _git(repo, "rev-parse", "--is-inside-work-tree")
    if not inside or inside.strip() != "true":
        return None, "not a git repository"
    shallow = _git(repo, "rev-parse", "--is-shallow-repository")
    if shallow and shallow.strip() == "true":
        return None, "shallow clone — history truncated"
    head_date = _git(repo, "log", "-1", "--format=%cI")
    if not head_date or not head_date.strip():
        return None, "no commits"
    head = _dt.datetime.fromisoformat(head_date.strip())
    since = (head - _dt.timedelta(days=CHURN_WINDOW_DAYS)).isoformat()
    log = _git(repo, "log", f"--since={since}", "--name-only",
               "--format=\x01%H\x01%aE\x01%cI", timeout=300)
    if log is None:
        return None, "git log failed"
    prefix = (_git(repo, "rev-parse", "--show-prefix") or "").strip()

    by_id = {t["id"]: t for t in facts.get("targets", []) or [] if t.get("id")}
    dir_to_cid: list[tuple[str, str]] = []
    for cid, c in containers.items():
        for tid in c.members:
            path = (by_id.get(tid, {}).get("path") or "").replace("\\", "/")
            d = path.rsplit("/", 1)[0] if "/" in path else path
            if d:
                dir_to_cid.append((prefix + d.rstrip("/") + "/", cid))
    dir_to_cid.sort(key=lambda x: (-len(x[0]), x[0]))

    commits: dict[str, int] = {}
    authors: dict[str, set[str]] = {}
    last: dict[str, str] = {}
    cur_author = cur_date = ""
    touched: set[str] = set()

    def _flush() -> None:
        for cid in touched:
            commits[cid] = commits.get(cid, 0) + 1
            if cur_author:
                authors.setdefault(cid, set()).add(cur_author)
            # git log is newest-first: the FIRST commit touching a container is its
            # most recent touch.
            last.setdefault(cid, cur_date)

    for line in log.splitlines() + ["\x01end\x01\x01"]:
        if line.startswith("\x01"):
            _flush()
            touched = set()
            parts = line.split("\x01")
            cur_author = parts[2] if len(parts) > 2 else ""
            cur_date = (parts[3] if len(parts) > 3 else "")[:10]
            continue
        f = line.strip().replace("\\", "/")
        if not f:
            continue
        for d, cid in dir_to_cid:
            if f.startswith(d):
                touched.add(cid)
                break

    per: dict[str, Any] = {}
    for cid in containers:
        per[cid] = {"available": True, "window_days": CHURN_WINDOW_DAYS,
                    "window_anchor": head_date.strip()[:10],
                    "churn_commits": commits.get(cid, 0),
                    "last_touched": last.get(cid),
                    "authors": len(authors.get(cid, set()))}
    return per, None


def system_identity(facts: dict[str, Any],
                    overrides: dict[str, Any] | None = None) -> tuple[str, str]:
    """``(system_id, system_name)`` for the whole software system — a deterministic pure
    function of the facts (so enrich's system-narrative pass and the datasheet builder
    agree on the id) with a hand override via ``rules/datasheet-overrides.yaml`` `system:`.
    Name defaults to the repo basename; the id is a stable ``system:<slug>``."""
    repo = ((facts.get("provenance") or {}).get("repo")) or ""
    name = re.split(r"[\\/]", repo.rstrip("\\/"))[-1] if repo else ""
    ov = (overrides or {}).get("system") or {}
    name = (ov.get("name") or name or "System").strip() or "System"
    slug = re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-") or "system"
    return f"system:{slug}", name


def _component_sheet(t: dict[str, Any], owner_cid: str, *, facts: dict[str, Any],
                     by_id: dict[str, dict[str, Any]], t2c: dict[str, str], containers,
                     comp_narratives: dict[str, Any], narrative_anchor: str,
                     cites: set[str], test_ids: set[str], tested_by: dict[str, set[str]],
                     measurements: dict[str, Any] | None, facts_hash: str,
                     overrides: dict[str, Any] | None = None) -> dict[str, Any]:
    """One component datasheet (plan §4.6): a build-target member rendered with the same
    block vocabulary as its container but at target altitude — its own metrics/technology,
    target→target fan-in/out (cross-container hops flagged), owned L2 components, tests,
    and the LLM narrative IF this component was salient enough to get one (else honest
    absence). Reuses the container block builders with a single-member list."""
    tid = t["id"]
    fan_in, fan_out = [], []
    for r in facts.get("relationships", []) or []:
        s, tt = r.get("source"), r.get("target")
        w = r.get("weight", 1) or 1
        if tt == tid and s in by_id:
            oc = t2c.get(s)
            fan_in.append({"from": s, "name": by_id[s].get("name", s), "weight": w,
                           "cross_container": oc != owner_cid,
                           "container": containers[oc].name if oc in containers else None})
        if s == tid and tt in by_id:
            oc = t2c.get(tt)
            fan_out.append({"to": tt, "name": by_id[tt].get("name", tt), "weight": w,
                            "cross_container": oc != owner_cid,
                            "container": containers[oc].name if oc in containers else None})
    fan_in.sort(key=lambda x: (-x["weight"], x["from"]))
    fan_out.sort(key=lambda x: (-x["weight"], x["to"]))
    l2_components = sorted({(comp.get("name") or comp.get("id"))
                            for comp in (t.get("components") or [])
                            if comp.get("name") or comp.get("id")})
    tags = t.get("tags") or []
    return {
        "id": tid,
        "name": t.get("llm_name") or t.get("name") or tid,
        "narrative": _narrative_block(tid, overrides, comp_narratives, narrative_anchor, cites),
        "purpose": {"text": t.get("description") or "",
                    "responsibilities": [r for r in (t.get("responsibilities") or []) if r][:3],
                    "enriched": bool(t.get("llm_name"))},
        "owns": {"path": (t.get("path") or "").replace("\\", "/"),
                 "namespaces": sorted(t.get("namespaces") or []),
                 "components": l2_components[:_SURFACE_CAP]},
        "metrics": _container_metrics([t]),
        "technology": _container_technology([t]),
        "fan_in": fan_in[:_TECH_CAP],
        "fan_out": fan_out[:_TECH_CAP],
        "footprint": _footprint(measurements, {tid}, facts_hash),
        "tests": _tests_block([tid], test_ids, tested_by),
        "health": {"language": t.get("language"),
                   "naming_confidence": t.get("naming_confidence"),
                   "needs_curation": "needs-curation" in tags,
                   "external": "external" in tags},
    }


def _system_sheet(facts: dict[str, Any], containers, cedges,
                  by_id: dict[str, dict[str, Any]], *, system_id: str, system_name: str,
                  sys_narratives: dict[str, Any], narrative_anchor: str, cites: set[str],
                  measurements: dict[str, Any] | None, facts_hash: str, l2: bool,
                  enriched: bool, overrides: dict[str, Any] | None = None) -> dict[str, Any]:
    """The whole-system datasheet (plan §4.6): the system narrative (synthesized 'what it
    does') over aggregate code metrics + a technology union + structural counts. Surfaced
    on the context view. Reuses the container metric/technology aggregators over ALL
    targets — system totals are never stored twice (§3.1)."""
    all_members = list(by_id.values())
    internal = [cid for cid in containers
                if not ({"external", "person"} & containers[cid].tags)]
    comp_total = sum(1 for c in containers.values()
                     for m in c.members if m in by_id and len(c.members) >= 2)
    langs = sorted({row.get("language", "") for t in all_members
                    for row in (t.get("metrics") or {}).get("by_language", []) or []} - {""})
    return {
        "id": system_id,
        "name": system_name,
        "narrative": _narrative_block(system_id, overrides, sys_narratives,
                                      narrative_anchor, cites | {system_id}),
        "metrics": _container_metrics(all_members),
        "technology": _container_technology(all_members),
        "counts": {"containers": len(containers),
                   "internal_containers": len(internal),
                   "external_containers": len(containers) - len(internal),
                   "components": comp_total,
                   "edges": len(cedges),
                   "languages": langs},
        "footprint": _footprint(measurements, set(by_id), facts_hash),
        "health": {"l2_extracted": l2, "enriched": enriched},
    }


def build_datasheets(facts: dict[str, Any], *,
                     layering_rules: dict[str, Any] | None = None,
                     risk_report: dict[str, Any] | None = None,
                     vitals: dict[str, Any] | None = None,
                     vitals_reason: str | None = None,
                     measurements: dict[str, Any] | None = None,
                     overrides: dict[str, Any] | None = None,
                     tests_facts: dict[str, Any] | None = None,
                     accept_hashes: set[str] | None = None) -> dict[str, Any]:
    """The machine-readable datasheet set (engine §1.6 — the GUI/agent API contract;
    datasheets/2 per the enrichment plan §7).

    Pure function of its inputs: every fan-in/out line cites its evidence layers, the
    public surface is honestly conditional on L2, and all honesty numbers come from the
    shipped single-source functions (§0.4). The datasheets/2 side inputs are gathered by
    :func:`run_datasheets` (risk report, git vitals, measurements sidecar, the hand-owned
    narrative overrides) and ECHOED here — risk numbers are never recomputed, a stale
    risk report / measurement is flagged, never half-trusted."""
    containers, t2c, cedges, container_description = _lift(facts)
    by_id = {t["id"]: t for t in facts.get("targets", []) or [] if t.get("id")}
    conf_c = confidence.container_confidence(facts)
    strata_c = scorecard.container_strata(facts)
    pair_layers, pair_conf = _pair_detail(facts, t2c)
    l2 = _l2_ran(facts)
    prov = facts.get("provenance") or {}
    enriched = prov.get("enrich_mode") not in (None, "no-llm")

    # datasheets/2 inputs (enrichment plan §7). Test adjacency reads the EXTRACTED facts
    # when supplied — curation usually excludes test projects from the model, and the
    # signal must survive that.
    facts_hash = content_hash(facts)
    risk_accept = (accept_hashes or set()) | {facts_hash}
    test_ids, tested_by = _tests_index(tests_facts or facts)
    cites = _cite_universe(facts, containers)
    narratives_proposed = facts.get("containers_narrative") or {}
    components_narrative = facts.get("components_narrative") or {}
    system_narrative = facts.get("system_narrative") or {}
    # LLM narratives are generated from the CURATED facts but stored in the enriched
    # file; their staleness anchor is the source hash enrich stamped, not this file's.
    narrative_anchor = prov.get("enrich_source_hash") or facts_hash

    # containers involved in a layering violation, for the health drift field.
    violating: set[str] = set()
    if layering_rules and (layering_rules.get("forbidden") or []):
        from .drift_report import check_layering
        for f in check_layering(facts, layering_rules):
            if f["status"] == "VIOLATION":
                for s, t in f["edges"]:
                    violating.update(c for c in (t2c.get(s), t2c.get(t)) if c)

    # public surface: symbols OTHERS use from this container (evidence on incoming
    # edges with visibility public) + member-provided COM identities.
    provided: dict[str, set[str]] = {}
    for r in facts.get("relationships", []) or []:
        ct = t2c.get(r.get("target"))
        if not ct:
            continue
        for e in r.get("evidence", []) or []:
            if e.get("type") in ("symbol_use", "include") and e.get("visibility") == "public":
                detail = e.get("detail")
                if detail:
                    provided.setdefault(ct, set()).add(detail)

    rows = []
    for cid in sorted(containers):
        c = containers[cid]
        members = [by_id[m] for m in sorted(c.members) if m in by_id]
        fan_in = [_fan_entry("from", s, containers[s].name if s in containers else s, e,
                             pair_layers.get((s, t), set()),
                             pair_conf.get((s, t), "low"))
                  for (s, t), e in sorted(cedges.items()) if t == cid]
        fan_in.sort(key=lambda x: (-x["weight"], x["from"]))
        fan_out = [_fan_entry("to", t, containers[t].name if t in containers else t, e,
                              pair_layers.get((s, t), set()),
                              pair_conf.get((s, t), "low"))
                   for (s, t), e in sorted(cedges.items()) if s == cid]
        fan_out.sort(key=lambda x: (-x["weight"], x["to"]))

        symbols = sorted(provided.get(cid, set()))
        for t in members:
            symbols += sorted(t.get("com_provides", []) or [])
        symbols = sorted(set(symbols))[:_SURFACE_CAP]
        if symbols:
            surface = {"available": True, "reason": "", "symbols": symbols}
        elif not l2:
            surface = {"available": False, "reason": "L2 not extracted", "symbols": []}
        else:
            surface = {"available": False,
                       "reason": "L2 ran — no public symbols observed in evidence",
                       "symbols": []}

        member_ids = sorted(c.members)
        if vitals is not None and cid in vitals:
            vit = vitals[cid]
        else:
            vit = {"available": False,
                   "reason": vitals_reason or "git vitals not computed"}
        # Component datasheets (plan §4.6) only for MULTI-member containers — a
        # single-member (model-Y) container already IS its one component, so a nested
        # sheet would just duplicate it. Matches build_containers' model-X materialization.
        components = []
        if len(members) >= 2:
            components = [_component_sheet(
                t, cid, facts=facts, by_id=by_id, t2c=t2c, containers=containers,
                comp_narratives=components_narrative, narrative_anchor=narrative_anchor,
                cites=cites, test_ids=test_ids, tested_by=tested_by,
                measurements=measurements, facts_hash=facts_hash, overrides=overrides)
                for t in members]
        rows.append({
            "id": cid,
            "name": c.name,
            "components": components,
            "narrative": _narrative_block(cid, overrides, narratives_proposed,
                                          narrative_anchor, cites),
            "purpose": {"text": c.description or container_description(c),
                        "enriched": enriched,
                        "grouped_by": _dominant_signal(members)},
            "owns": {"members": member_ids,
                     "paths": sorted({(t.get("path") or "").replace("\\", "/")
                                      for t in members if t.get("path")}),
                     "namespaces": sorted({ns for t in members
                                           for ns in (t.get("namespaces") or [])})},
            "metrics": _container_metrics(members),
            "technology": _container_technology(members),
            "fan_in": fan_in,
            "fan_out": fan_out,
            "public_surface": surface,
            "footprint": _footprint(measurements, set(member_ids), facts_hash),
            "vitals": vit,
            "risk": _risk_echo(risk_report, risk_accept, cid),
            "tests": _tests_block(member_ids, test_ids, tested_by),
            "health": {"coverage_stratum": strata_c.get(cid, "none"),
                       "mean_confidence": conf_c.get(cid),
                       "needs_curation": "needs-curation" in c.tags,
                       "external": "external" in c.tags or "person" in c.tags,
                       "drift": "violating" if cid in violating else "stable"},
        })
    system_id, system_name = system_identity(facts, overrides)
    # `system_narrative` is a single flat record; _narrative_block (shared with containers/
    # components) keys by id, so wrap it as {system_id: record} for the lookup.
    sys_narratives = {system_id: system_narrative} if system_narrative else {}
    system = _system_sheet(facts, containers, cedges, by_id, system_id=system_id,
                           system_name=system_name, sys_narratives=sys_narratives,
                           narrative_anchor=narrative_anchor, cites=cites,
                           measurements=measurements, facts_hash=facts_hash, l2=l2,
                           enriched=enriched, overrides=overrides)
    return {"schema": DATASHEETS_SCHEMA, "derived_from_hash": facts_hash,
            "l2_extracted": l2, "system": system, "containers": rows}


def _fmt_bytes(n: int) -> str:
    """Deterministic human size: B / KiB / MiB with one decimal."""
    if n < 1024:
        return f"{n} B"
    if n < 1024 * 1024:
        return f"{n / 1024:.1f} KiB"
    return f"{n / (1024 * 1024):.1f} MiB"


def _render_narrative(n: dict[str, Any]) -> list[str]:
    """The plan-§4 narrative block: loud source chip, hard absence, cited bullets."""
    if n["source"] == "none":
        return [f"> _Narrative: {n['reason']}._", ""]
    if n["source"] == "human":
        chip = "Human-written (rules/datasheet-overrides.yaml)"
    else:
        chip = f"LLM-generated ({n['model_id'] or 'unknown model'})" \
               + (" · POSSIBLY STALE — facts changed since generation"
                  if n["stale"] else "")
    lines = [f"> **Narrative — {chip}**", ">"]
    for para in (n["abstract_md"] or "").strip().splitlines():
        lines.append(f"> {para}" if para else ">")
    for kp in n["key_points"]:
        cited = (" _(cites: " + ", ".join(f"`{c}`" for c in kp["cites"]) + ")_"
                 if kp["cites"] else "")
        lines.append(f"> - {kp['text']}{cited}")
    if n.get("stale_citations"):
        lines.append("> - ⚠ unresolvable citation(s): "
                     + ", ".join(f"`{c}`" for c in n["stale_citations"]))
    lines.append("")
    return lines


def render_datasheet(row: dict[str, Any]) -> str:
    """One container's datasheet as markdown — the §1.6 / enrichment-§7 specimen shape.
    Render order keeps the cited deterministic fields adjacent to the narrative so a
    plausible-but-wrong abstract never stands alone (plan §9 threat c)."""
    p = row["purpose"]
    qualifier = "name enriched; " if p["enriched"] else ""
    grouped = f"grouped by `{p['grouped_by']}`" if p["grouped_by"] else "ungrouped"
    members = row["owns"]["members"]
    lines = [f"## {row['name']}", ""]
    lines += _render_narrative(row["narrative"])
    lines += [f"**Purpose** — {p['text']} _({qualifier}{grouped})_", "",
              f"**Owns** — {len(members)} target(s): "
              + ", ".join(f"`{m}`" for m in members) + ".", ""]

    m = row["metrics"]
    if m["available"]:
        t = m["total"]
        lines += [f"**Metrics** — {t['files']} file(s): {t['code']} code / "
                  f"{t['comment']} comment / {t['blank']} blank line(s) · "
                  f"{m['todo_count']} TODO/FIXME/HACK marker(s) _({m['engine']})_.", ""]
        if len(m["by_language"]) > 1:
            lines += ["| Language | Files | Code | Comment | Blank |",
                      "|---|---:|---:|---:|---:|"]
            lines += [f"| {r['language']} | {r['files']} | {r['code']} | "
                      f"{r['comment']} | {r['blank']} |" for r in m["by_language"]]
            lines.append("")
    else:
        lines += [f"**Metrics** — _{m['reason']}._", ""]
    tech = row["technology"]
    if tech["packages"]:
        more = (f" (+{tech['packages_total'] - len(tech['packages'])} more)"
                if tech["packages_total"] > len(tech["packages"]) else "")
        lines += ["**Technology** — packages: "
                  + ", ".join(f"`{x}`" for x in tech["packages"]) + f"{more}.", ""]
    else:
        lines += ["**Technology** — _no package references in evidence._", ""]

    def _fan(label: str, entries: list[dict[str, Any]], key: str) -> str:
        if not entries:
            return f"**{label}** — _nothing in-model_."
        bits = []
        for e in entries:
            layers = "+".join(e["evidence_layers"]) or "L0"
            bits.append(f"`{e['name']}` (weight {e['weight']}, {layers} {e['kind']}"
                        f"{', declared' if e['declared'] else ''})")
        return f"**{label}** — " + ", ".join(bits) + "."

    lines += [_fan("Depended on by", row["fan_in"], "from"),
              _fan("Depends on", row["fan_out"], "to"), ""]
    s = row["public_surface"]
    if s["available"]:
        lines.append("**Public surface** — " + ", ".join(f"`{x}`" for x in s["symbols"])
                     + ".")
    else:
        lines.append(f"**Public surface** — _{s['reason']}; no symbol-level surface "
                     "available on this run._")
    fp = row["footprint"]
    if fp["available"]:
        stale = " · ⚠ STALE — the facts changed since this measurement" \
            if fp["stale"] else ""
        lines += ["", f"**Footprint** — {_fmt_bytes(fp['size_bytes'])} across "
                  f"{fp['artifacts']} artifact(s), measured {fp['measured_at'] or '?'} "
                  f"at commit `{(fp['commit'] or 'unknown')[:12]}`{stale}."]
    else:
        lines += ["", f"**Footprint** — _{fp['reason']}._"]
    h = row["health"]
    conf = f"{h['mean_confidence']:.2f}" if h["mean_confidence"] is not None else "—"
    lines += ["",
              f"**Health** — coverage {h['coverage_stratum']} · mean confidence {conf} · "
              + ("flagged `needs-curation`" if h["needs_curation"]
                 else "not flagged `needs-curation`")
              + f" · drift: {h['drift']}."]
    v = row["vitals"]
    if v.get("available"):
        last = v["last_touched"] or "not in window"
        lines.append(f"**Vitals** — {v['churn_commits']} commit(s) in the "
                     f"{v['window_days']} days before HEAD · last touched {last} · "
                     f"{v['authors']} author(s).")
    else:
        lines.append(f"**Vitals** — _{v.get('reason', 'unavailable')}._")
    r = row["risk"]
    if r.get("available"):
        if r["finding_kinds"]:
            extras = []
            if r["instability_I"] is not None:
                extras.append(f"I={r['instability_I']}")
            if r["abstractness_A"] is not None:
                extras.append(f"A={r['abstractness_A']}")
            if r["distance_D"] is not None:
                extras.append(f"D={r['distance_D']}")
            suffix = (" (" + ", ".join(extras) + ")") if extras else ""
            lines.append("**Risk** — findings: "
                         + ", ".join(f"`{k}`" for k in r["finding_kinds"])
                         + f"{suffix} _(echoed from risk-report.json)_.")
        else:
            lines.append("**Risk** — no findings for this container "
                         "_(echoed from risk-report.json)_.")
    else:
        lines.append(f"**Risk** — _{r.get('reason', 'unavailable')}._")
    te = row["tests"]
    if te["test_targets_total"]:
        lines.append(f"**Tests** — {te['test_targets_total']} test target(s) reference "
                     f"this container; {te['members_with_tests']}/{te['members']} "
                     f"member(s) referenced by a test _(adjacency proxy, not coverage)_.")
    else:
        lines.append("**Tests** — _no in-model test target references this container "
                     "(adjacency proxy, not coverage)._")
    lines.append("")
    return "\n".join(lines)



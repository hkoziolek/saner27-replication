DATASHEETS_SCHEMA = "datasheets/3"
TOUR_SCHEMA = "datasheets-tour/1"
_SURFACE_CAP = 25          # public-surface symbols per datasheet (a manual, not a dump)
_TECH_CAP = 15             # package names per technology fingerprint (a manual, not a dump)
_TEST_CAP = 10             # test targets listed per datasheet
_TOUR_MAX_HOPS = 10
_CONF_RANK = {"high": 0, "medium": 1, "low": 2}

# The pinned test-target heuristic (datasheet plan §6.3): a name or path SEGMENT
# `test`/`tests` (delimited — `Contest.csproj` does not match). A *proxy* for test
# adjacency, honestly labeled as such — never called "coverage".
_TEST_SEGMENT = re.compile(r"(^|[/._\-])tests?($|[/._\-])", re.IGNORECASE)


def _is_test_target(t: dict[str, Any]) -> bool:
    name = t.get("name") or ""
    path = (t.get("path") or "").replace("\\", "/")
    return bool(_TEST_SEGMENT.search(name) or _TEST_SEGMENT.search(path))


def _lift(facts: dict[str, Any]):
    """The generator's two-step container lift — imported lazily because
    ``generate_structurizr`` imports this module at its top (a top-level import here
    would be circular)."""
    from .generate_structurizr import (_container_description,
                                       build_container_edges, build_containers)
    containers = build_containers(facts)
    t2c = {m: c.cid for c in containers.values() for m in c.members}
    cedges = build_container_edges(facts, t2c)
    return containers, t2c, cedges, _container_description


def _edge_layer_set(rel: dict[str, Any]) -> set[str]:
    return {layer for layer in (confidence._LAYER_OF.get(e.get("type"))
                                for e in rel.get("evidence", []) or []) if layer}


def _l2_ran(facts: dict[str, Any]) -> bool:
    """Did any symbol/include-level extraction contribute evidence to this run?"""
    return any(e.get("type") in ("symbol_use", "include")
               for r in facts.get("relationships", []) or []
               for e in r.get("evidence", []) or [])


def _pair_detail(facts: dict[str, Any], t2c: dict[str, str]):
    """Per container pair: evidence layers + the strongest contributing confidence —
    so a datasheet's fan-in line can say "(weight 7, L1 project_ref + L2 symbol_use)"."""
    layers: dict[tuple[str, str], set[str]] = {}
    conf: dict[tuple[str, str], str] = {}
    for r in facts.get("relationships", []) or []:
        cs, ct = t2c.get(r.get("source")), t2c.get(r.get("target"))
        if not cs or not ct or cs == ct:
            continue
        key = (cs, ct)
        layers.setdefault(key, set()).update(_edge_layer_set(r))
        c = r.get("confidence")
        if c in _CONF_RANK and _CONF_RANK[c] < _CONF_RANK.get(conf.get(key, "low"), 99):
            conf[key] = c
        conf.setdefault(key, c if c in _CONF_RANK else "low")
    return layers, conf


def _fan_entry(direction_key: str, other: str, other_name: str, e: dict[str, Any],
               layers: set[str], conf: str) -> dict[str, Any]:
    return {direction_key: other, "name": other_name, "weight": e["weight"],
            "kind": e.get("kind") or "uses", "declared": bool(e["declared"]),
            "evidence_layers": sorted(layers), "confidence": conf}


def _dominant_signal(members: list[dict[str, Any]]) -> str | None:
    """The most common ``grouped_by.signal`` among members (ties broken by name)."""
    counts: dict[str, int] = {}
    for t in members:
        sig = (t.get("grouped_by") or {}).get("signal")
        if sig:
            counts[sig] = counts.get(sig, 0) + 1
    if not counts:
        return None
    return sorted(counts.items(), key=lambda kv: (-kv[1], kv[0]))[0][0]



# --- C4 description/technology synthesis (model-completeness; §9.2) -------------
# Every emitted element/relationship gets a non-empty description + technology so the
# Structurizr `model.*.description` / `model.relationship.technology` inspections pass even
# in the deterministic --no-llm baseline. Hand-authored `descriptions:` (§7.4) override the
# fallbacks; the LLM enrichment path overrides them further. All synthesis is deterministic.

# Relationship technology by evidence kind, strongest structural signal first (§5/§6.2).
_EDGE_TECH = (
    ("project_ref", ".NET project reference"),
    ("package_ref", "NuGet package reference"),
    ("link", "Native link (static/shared library)"),
    ("interop", "Native interop (P/Invoke / COM / C++-CLI)"),
    ("contract", "Shared contract (IDL / .proto)"),
    ("include", "C/C++ include dependency"),
    ("symbol_use", "Symbol reference"),
    ("runtime", "Runtime call"),
)


def _edge_technology(e: dict[str, Any]) -> str:
    """A deterministic, human technology label for a container edge from its evidence tags."""
    tags = e.get("tags", set())
    for key, tech in _EDGE_TECH:
        if key in tags or any(t.startswith(key + ":") for t in tags):
            return tech
    return "Dependency"


def _container_description(c: "Container") -> str:
    """Hand-authored description if present, else a deterministic build-graph summary so the
    container is never description-less (Structurizr ``model.container.description``)."""
    if c.description:
        return c.description
    names = sorted(c.member_names or c.members)
    tech = c.technology or "Build target group"
    if not names:
        return tech
    shown = ", ".join(names[:3]) + (f" (+{len(names) - 3} more)" if len(names) > 3 else "")
    if len(names) == 1:
        return f"{tech}: {shown}."
    return f"{tech} grouping {len(names)} build targets: {shown}."


def _container_technology(c: "Container") -> str:
    """The curated technology, else a deterministic fallback from the element's tags so a
    container never trips the Structurizr ``model.container.technology`` inspection (§9.2)."""
    if c.technology:
        return c.technology
    if "contract" in c.tags:
        return "Interface contract"
    if "person" in c.tags:
        return "Person / actor"
    if "external" in c.tags:
        return "External system"
    if "csharp" in c.tags or "clr" in c.tags:
        return ".NET"
    if "cpp" in c.tags:
        return "C/C++"
    return "Software container"


def _component_description(comp: "Component") -> str:
    """Deterministic description for a component/code element from its tier tags (§6.3)."""
    if comp.description:
        return comp.description
    if "target" in comp.tags:
        return f"Build target `{comp.name}`."
    if "code" in comp.tags:
        return f"Class or type `{comp.name}`."
    if "source:namespace" in comp.tags:
        return f"Namespace `{comp.name}`."
    if "source:subdir" in comp.tags:
        return f"Source directory `{comp.name}`."
    return f"Component `{comp.name}`."


# --- element tag derivation (§9.2) ---------------------------------------------

def _element_tags(target: dict[str, Any]) -> set[str]:
    """Every element tag: language, technology, layer, needs-curation, external (§9.2)."""
    tags: set[str] = set()
    lang = target.get("language")
    if lang:
        tags.add(lang)
    tech = target.get("technology")
    if tech:
        tags.add(tech)
    for t in target.get("tags", []):
        # carry the curation/extraction tags filtered views key off (§9.2).
        if (t in ("needs-curation", "external", "person", "contract", "com", "clr")
                or t.startswith(("partial:", "layer:", "adr:", "interop:", "iac:", "runtime:"))):
            tags.add(t)
    if target.get("external"):
        tags.add("external")
    return tags


def _is_boundary_member(t: dict[str, Any]) -> bool:
    """A member target that belongs to the system BOUNDARY rather than the system under
    study: an external dependency (a transitive NuGet/package target) or a person. A
    container is only a boundary container — tagged ``external``/``person`` — when EVERY
    member is a boundary element; one bundled external package must not make a first-party
    container a boundary (and thus un-narratable). See :func:`build_containers`."""
    return bool(t.get("external")
                or {"external", "person"} & set(t.get("tags", []) or []))


def decide_model_shape(facts: dict[str, Any], rules: Any = None) -> tuple[str, int]:
    """The D§2.3 auto-select: ``(shape, N)`` where ``N`` = curated module-target count.

    Shape **Y** iff ``N <= MODEL_Y_MAX`` (Y's module-containers become the top Container
    view, so they must fit its budget), else **X**. ``model_shape: x|y`` in
    ``mapping-rules.yaml`` pins the shape (the D§2.3 anti-flapping valve); ``auto`` is the
    default. Boundary-promoted externals/persons are their own containers under either
    shape, so they don't count toward ``N``. Pure function of the curated facts + rules.
    """
    n = sum(1 for t in facts.get("targets", [])
            if not t.get("external") and not t.get("boundary_kind"))
    pin = getattr(rules, "model_shape", "auto") if rules is not None else "auto"
    if pin in ("x", "y"):
        return pin, n
    return ("y" if n <= MODEL_Y_MAX else "x"), n


def _nest_tier(c: Container, t: dict[str, Any]) -> None:
    """Nest one target's §6.3 child tier into container *c* (Model Y / promoted targets).

    A plain container shows the NAMESPACE component tier; a ``code_view`` container shows
    the CLASSES of the matching namespace(s) (the C4 code altitude) instead; an
    ``expand_classes`` promotion (D§5) shows every namespace's classes.
    """
    for comp in t.get("components", []) or []:
        if c.code_view:
            if c.code_view in comp.get("key", "") or c.code_view in comp.get("name", ""):
                for code in comp.get("code", []) or []:
                    c.components.append(Component(cid=code["id"],
                                                  name=code.get("name", code["id"]),
                                                  tags={"Component", "code"}))
            # a non-matching namespace contributes nothing to a code view (scoped, §9.1).
        elif c.expand_classes:
            for code in comp.get("code", []) or []:
                c.components.append(Component(cid=code["id"],
                                              name=code.get("name", code["id"]),
                                              tags={"Component", "code"}))
        else:
            ctags = {"Component"}
            if comp.get("source"):
                ctags.add(f"source:{comp['source']}")
            c.components.append(Component(cid=comp["id"], name=comp.get("name", comp["id"]),
                                          tags=ctags))


def _target_component(t: dict[str, Any]) -> Component:
    """One member build target as a C4 component (D§3.1, Model X).

    ``cid`` = the target id — the slug-stability key: the same target referenced as an
    edge endpoint or later promoted to a container resolves to the SAME identifier
    (D§9, the layout-merge precondition). The description is target-derived and
    deterministic (D§8): names are raw target names, no LLM.
    """
    name = t.get("name", t["id"])
    tech = t.get("technology") or t.get("type") or t.get("language") or ""
    desc = f"Build target {name} ({tech})." if tech else f"Build target {name}."
    return Component(cid=t["id"], name=name, description=desc,
                     tags={"Component", "target"} | _element_tags(t))


def _group_label(theme: str | None, parent: str | None) -> str | None:
    """The rendered ``group{}`` label for a theme that may sit under a cosmetic parent.

    v1 flattens the two tiers into one label (``"Middleware / PubSub"``) because
    ``Container.group`` is single-valued and nested ``group{}`` needs the
    ``structurizr.groupSeparator`` model property — the deferred spike
    (container-groups plan §4.2/§4.3). No parent → the theme label unchanged."""
    if theme and parent:
        return f"{parent} / {theme}"
    return theme or None


def build_containers(facts: dict[str, Any], shape: str = "x",
                     promote_expanded: bool = False) -> dict[str, Container]:
    """Aggregate curated targets into the C4 container/component hierarchy for *shape*.

    Model **X** (default): container = curated theme; each MULTI-target container
    materializes its member targets as components (D§3.1); single-target containers have
    nothing to drill. With *promote_expanded*, an ``expand``-flagged target (D§5) is
    promoted out of its theme to a container of its own (namespace/class tier nested),
    the theme wrapping both via a cosmetic ``group{}``.

    Model **Y**: every module target IS a container (cid = target id), its curated theme
    becomes its ``group`` label, and its namespace tier nests natively (D§2.2/D§3.2).
    Boundary-promoted externals/persons are their own containers under either shape.

    *shape*/*promote_expanded* are only passed by the generator's :func:`run` — the
    facts-level consumers (``query``/``serve``/confidence/datasheets) call
    ``build_containers(facts)`` and keep the pure curated ``container_id`` grouping:
    the model shape and the D§5 promotion are DSL-RENDERING choices, not facts
    (D§0.1#7 — the GUI inherits the emitted artifacts later; its API stays at the
    curated altitude until GUI Stage 3 takes this up).
    """
    containers: dict[str, Container] = {}
    member_targets: dict[str, list[dict[str, Any]]] = {}
    # every container's member target dicts (both the standalone and grouped paths) — so the
    # post-loop boundary pass can ask "are ALL members external?" before keeping the tag.
    members_by_cid: dict[str, list[dict[str, Any]]] = {}
    # X themes that lost a member to an expand promotion still wrap their remaining
    # members in the theme group, so the promoted sibling stays visually attached (D§5).
    # Value is ``(theme_name, container_parent)`` — with a parent tier present the two
    # flatten into one "Parent / Theme" group label (container-groups plan §4.2, v1:
    # single-level groups only; true nesting is the deferred groupSeparator spike).
    expanded_themes: dict[str, tuple[str, str | None]] = {}
    for t in facts.get("targets", []):
        tid = t["id"]
        grouped = t.get("container_id", tid) != tid
        # A module target stands alone as a container when the shape says so (Y) or the
        # curation asked for the deep path (expand, D§5). Boundary promotions keep their
        # existing single-target-container handling under either shape.
        standalone = ((shape == "y" or (promote_expanded and t.get("expand")))
                      and not t.get("boundary_kind"))
        if standalone:
            c = containers.get(tid)
            if c is None:
                c = Container(cid=tid, name=t.get("name", tid))
                containers[tid] = c
            c.members.append(tid)
            c.member_names.append(t.get("name", tid))
            members_by_cid.setdefault(tid, []).append(t)
            if t.get("technology"):
                c.technology = t["technology"]
            c.tags |= _element_tags(t)
            if grouped:
                # Model Y theme / D§5 promoted sibling: the group label is the theme,
                # prefixed by the cosmetic parent when one exists (flattened, plan §4.2).
                c.group = _group_label(t.get("container_name"),
                                       t.get("container_parent"))
                if t.get("expand"):
                    expanded_themes[t.get("container_id", tid)] = (
                        t.get("container_name", ""), t.get("container_parent"))
            if t.get("expand_classes"):
                c.expand_classes = True
            if t.get("code_view"):
                c.code_view = t["code_view"]
            _nest_tier(c, t)
            continue
        cid = t.get("container_id", tid)
        cname = t.get("container_name", t.get("name", cid))
        c = containers.get(cid)
        if c is None:
            c = Container(cid=cid, name=cname)
            containers[cid] = c
        c.members.append(tid)
        c.member_names.append(t.get("name", tid))
        if t.get("technology"):
            c.technology = t["technology"]
        # hand-authored container description (curate stamps it on every member, §7.4).
        if t.get("container_description") and not c.description:
            c.description = t["container_description"]
        c.tags |= _element_tags(t)
        if t.get("component_view"):
            c.component_view = True
        # Model X: a curated container whose members carry a cosmetic parent renders
        # inside that parent's `group{}` boundary (container-groups plan §4.1). Every
        # member carries the same label (stamped per-rule by curate), so first-set wins.
        if t.get("container_parent") and not c.group:
            c.group = t["container_parent"]
        member_targets.setdefault(cid, []).append(t)
        members_by_cid.setdefault(cid, []).append(t)
    # A container is a BOUNDARY (external/person) container only when EVERY member is a
    # boundary element. A first-party container that merely bundles a transitive external
    # package (e.g. an Aspire AppHost referencing Aspire.Hosting.AppHost) stays first-party
    # — and thus narratable; one external member must not tag the whole container external.
    for cid, c in containers.items():
        members = members_by_cid.get(cid)
        if members and not all(_is_boundary_member(m) for m in members):
            c.tags.discard("external")
            c.tags.discard("person")
    if shape != "y":
        # D§3.1: a multi-target container's members become its target-components — the
        # build graph one zoom below the curation grouping. The namespace tier is NOT
        # rendered here (it moved to the D§5 deep path); a single-target container
        # materializes nothing (nothing to drill, D§3.1 singleton resolution).
        for cid, ts in member_targets.items():
            c = containers[cid]
            if len(c.members) >= 2:
                for t in ts:
                    c.components.append(_target_component(t))
        for theme_cid, (theme_name, theme_parent) in expanded_themes.items():
            if theme_cid in containers and theme_name:
                containers[theme_cid].group = _group_label(theme_name, theme_parent)
    # deterministic component order within each container; pin each component's description
    # from its CLEAN (pre-reconciler) tier name so disambiguation (§8.3) can't leak the
    # "(owner)" qualifier into the description text.
    for c in containers.values():
        c.components.sort(key=lambda x: x.cid)
        for comp in c.components:
            comp.description = _component_description(comp)
    return containers


# --- relationship tags (§9.2) --------------------------------------------------

def _edge_tags(r: dict[str, Any]) -> set[str]:
    """Relationship tags: kind, evidence kinds, is_declared, confidence, drift (§9.2)."""
    tags: set[str] = set()
    if r.get("kind"):
        tags.add(f"kind:{r['kind']}")
    for ev in r.get("evidence", []):
        et = ev.get("type")
        if et:
            tags.add(et)  # link / include / symbol_use / project_ref / package_ref
    if r.get("is_declared_dependency"):
        tags.add("declared")
    conf = r.get("confidence")
    if conf:
        tags.add(f"confidence:{conf}")
    for t in r.get("tags", []):
        # drift / curation edge tags: new-dependency, suspicious-declared, private-link, ...
        tags.add(t)
    return tags


def build_container_edges(facts: dict[str, Any], target_to_container: dict[str, str]) -> dict:
    """Aggregate target edges into container edges (skip intra-container, merge parallel)."""
    edges: dict[tuple[str, str], dict[str, Any]] = {}
    for r in facts.get("relationships", []):
        cs = target_to_container.get(r["source"])
        ct = target_to_container.get(r["target"])
        if cs is None or ct is None or cs == ct:
            continue
        key = (cs, ct)
        e = edges.setdefault(key, {"kind": r.get("kind"), "weight": 0, "tags": set(),
                                   "declared": False})
        e["weight"] += r.get("weight", 0)
        e["declared"] = e["declared"] or r.get("is_declared_dependency", False)
        # a curated kind on any contributing edge wins as the merged label (deterministic:
        # first by sorted relationship order, see below).
        if r.get("kind") and not e["kind"]:
            e["kind"] = r["kind"]
        e["tags"] |= _edge_tags(r)
    return edges


def build_component_edges(facts: dict[str, Any], target_to_container: dict[str, str],
                          materialized: set[str]) -> dict:
    """Project target->target edges to the COMPONENT altitude (drill-down plan D§4.1).

    *materialized* is the set of target ids emitted as components (Model X: members of
    multi-target containers; empty under Model Y, where targets are containers and
    :func:`build_container_edges` already carries every edge). Per curated relationship:

      - **intra-container**, both endpoints materialized -> a component->component edge
        (the edges ``build_container_edges`` discards at its ``cs == ct`` skip — un-hidden
        here at the altitude where they are true).
      - **cross-container** -> the component->container HALF-edge for each materialized
        endpoint (``s -> parent(t)`` / ``parent(s) -> t``). Deviation from D§4.1's
        component->component, justified by the D§12.1 spike: a Structurizr component view's
        ``include *`` never pulls a FOREIGN component in, so a cross-boundary
        component->component edge renders nowhere; the half-edges render in each side's
        Component view, and the container view still shows only the explicit container
        edge (a component endpoint excludes an edge from that view).
      - neither endpoint materialized -> covered by the container edge; nothing emitted.

    No new structure is invented: every edge here is a re-projection of a curated
    relationship that already passed curate's significance rules (declared edges always
    kept; weak non-declared edges already dropped), so component and container altitudes
    can never disagree (D§4.1/Q10). Merge + ordering mirror ``build_container_edges``.
    """
    edges: dict[tuple[str, str], dict[str, Any]] = {}
    for r in facts.get("relationships", []):
        s, t = r["source"], r["target"]
        cs = target_to_container.get(s)
        ct = target_to_container.get(t)
        if cs is None or ct is None:
            continue
        pairs: list[tuple[str, str]] = []
        if cs == ct:
            if s != t and s in materialized and t in materialized:
                pairs.append((s, t))
        else:
            if s in materialized:
                pairs.append((s, ct))
            if t in materialized:
                pairs.append((cs, t))
        for key in pairs:
            e = edges.setdefault(key, {"kind": r.get("kind"), "weight": 0, "tags": set(),
                                       "declared": False})
            e["weight"] += r.get("weight", 0)
            e["declared"] = e["declared"] or r.get("is_declared_dependency", False)
            if r.get("kind") and not e["kind"]:
                e["kind"] = r["kind"]
            e["tags"] |= _edge_tags(r)
    return edges


def build_namespace_edges(facts: dict[str, Any], emitted_components: set[str]) -> dict:
    """Project the §6.3 component-altitude relationships to component->component edges.

    These are the ``…/component:<ns>`` relationships — the Roslyn helper's intra-project
    namespace->namespace ``symbol_use`` edges (``RoslynWorker.cs``; kept verbatim by curate,
    ``apply_mapping_rules`` D§6.3) that live one zoom BELOW the curation grid. They are the
    INTERIOR of a Model-Y module-container (and of a D§5 ``expand`` promotion): without them
    the namespace tier renders edgeless, because :func:`build_component_edges` only projects
    target->target edges (D§4 carried only the inter-target altitude — this closes that gap).

    *emitted_components* is the set of component cids actually materialized in the model
    (``{comp.cid for c in containers for comp in c.components}``). An edge is kept iff BOTH
    endpoints are emitted components: a namespace excluded or aggregated by curate
    (``_curate_components``) leaves no element to attach to, so its edges are honestly
    dropped rather than dangling — the same "validate endpoints against real components"
    guard the Roslyn helper applies on emission. The helper only emits INTRA-project ns
    edges, so both endpoints always share one owning target = one container; there is no
    cross-boundary case (and thus no D§4.1 half-edge complication) at this altitude.

    Merge + ordering mirror :func:`build_component_edges`; the disjoint key space
    (``/component:`` ids vs target/container ids) lets the caller merge the two dicts.
    """
    edges: dict[tuple[str, str], dict[str, Any]] = {}
    for r in facts.get("relationships", []):
        s, t = r["source"], r["target"]
        if "/component:" not in s or "/component:" not in t:
            continue
        if s == t or s not in emitted_components or t not in emitted_components:
            continue
        key = (s, t)
        e = edges.setdefault(key, {"kind": r.get("kind"), "weight": 0, "tags": set(),
                                   "declared": False})
        e["weight"] += r.get("weight", 0)
        e["declared"] = e["declared"] or r.get("is_declared_dependency", False)
        if r.get("kind") and not e["kind"]:
            e["kind"] = r["kind"]
        e["tags"] |= _edge_tags(r)
    return edges


# --- deterministic cross-element naming reconciler (§8.3) -----------------------

def _stable_qualifier(element_id: str) -> str:
    """A short, stable, human-ish qualifier derived from the stable id (§8.3 step 2).

    Uses the namespace + key segments of the id so the disambiguation is reproducible
    and edit-order-independent. e.g. ``csharp:csproj:src/Web/Toy.Web.csproj`` -> ``Web``.
    """
    # component/code child ids carry their OWNING element before "/component:" or "/code:";
    # qualify duplicate namespaces/classes by that owner so two modules' identically-named
    # namespaces read "cv (opencv_core)" / "cv (opencv_imgproc)" rather than colliding (§9.1).
    for sep in ("/component:", "/code:"):
        if sep in element_id:
            owner = element_id.split(sep, 1)[0]
            oseg = [s for s in owner.split(":") if s]
            okey = (oseg[-1] if oseg else owner).replace("\\", "/")
            oparts = [p for p in okey.split("/") if p]
            return oparts[-1] if oparts else owner
    segs = [s for s in element_id.split(":") if s]
    key = segs[-1] if segs else element_id
    key = key.replace("\\", "/")
    # prefer the parent folder of a path-like key (more informative than the basename).
    parts = [p for p in key.split("/") if p]
    if len(parts) >= 2:
        return parts[-2]
    return parts[-1] if parts else element_id


def _convention(name: str) -> str:
    if _SNAKE.match(name):
        return "snake"
    if _SPACED_TITLE.match(name):
        return "spaced"
    if " " not in name and name[:1].islower():
        return "camel"
    return "other"


def _mixed_convention_outliers(named: list[tuple[str, str]]) -> set[str]:
    """The ids the §8.3 reconciler flags ``needs-curation``: the *minority*-convention
    names among *named*, never the whole set. Empty when the names share a single
    convention (or are all ``other``). A single odd sibling must not taint its well-named
    peers, so only names outside the sole majority convention are flagged; on a tie for the
    majority (no clear house style) every conventioned name is an outlier. ``other``
    (unclassifiable) names are never flagged and never count toward the majority.
    Deterministic: depends only on the names, not their order."""
    conv = {eid: _convention(n) for eid, n in named}
    counts = Counter(c for c in conv.values() if c != "other")
    if len(counts) <= 1:
        return set()
    top = max(counts.values())
    leaders = [c for c, k in counts.items() if k == top]
    majority = leaders[0] if len(leaders) == 1 else None   # tie -> no house style
    return {eid for eid, c in conv.items() if c != "other" and c != majority}


def reconcile_names(siblings: list[tuple[str, str]],
                    name_overrides: dict[str, str]) -> tuple[dict[str, str], bool]:
    """Deterministic sibling-set naming reconciler (§8.3).

    *siblings* is a list of ``(element_id, current_name)``. Returns
    ``(id -> reconciled_name, mixed_conventions)``:
      1. ``name_overrides`` hard-win over any (LLM-)supplied name.
      2. disambiguate duplicate display names by appending a stable id-derived qualifier.
      3. report whether the surviving names mix conventions (caller tags `needs-curation`).
    Deterministic / golden-test-safe: results depend only on ids + names, not order.
    """
    resolved: dict[str, str] = {}
    for eid, name in siblings:
        resolved[eid] = name_overrides.get(eid, name)

    # (2) disambiguate duplicates deterministically.
    by_name: dict[str, list[str]] = {}
    for eid in sorted(resolved):              # sorted -> order-independent
        by_name.setdefault(resolved[eid], []).append(eid)
    for name, ids in by_name.items():
        if len(ids) <= 1:
            continue
        for eid in ids:
            # a pinned name is authoritative even if it now collides — do not mangle it.
            if eid in name_overrides:
                continue
            resolved[eid] = f"{name} ({_stable_qualifier(eid)})"

    # (3) mixed-convention detection over the surviving names. `mixed` stays a bool for the
    # public API (and unit tests); _apply_reconciler calls _mixed_convention_outliers
    # directly so it can flag only the outliers and skip external seams. Equivalent bool:
    # outliers exist iff >=2 distinct non-"other" conventions are present.
    mixed = bool(_mixed_convention_outliers(list(resolved.items())))
    return resolved, mixed


def _apply_reconciler(containers: dict[str, Container], name_overrides: dict[str, str]) -> None:
    """Run the §8.3 reconciler over the container sibling set and each component set.

    Naming is reconciled for *every* sibling, but the ``needs-curation`` mixed-convention
    flag is applied surgically: only to the minority-convention outliers, and never to an
    external/person boundary or contract seam. Those are auto-named from a filename or id
    (e.g. ``contract:proto:basket`` -> "basket"), not curated container names, so they must
    neither receive the flag nor taint the convention check for the hand-named containers
    around them (otherwise one lowercase seam paints a whole well-curated model yellow).
    """
    # containers are siblings of the system.
    sibs = [(c.cid, c.name) for c in containers.values()]
    resolved, _ = reconcile_names(sibs, name_overrides)
    for c in containers.values():
        c.name = resolved[c.cid]
    curated = [(c.cid, c.name) for c in containers.values()
               if not (c.tags & {"external", "person"})]
    for cid in _mixed_convention_outliers(curated):
        containers[cid].tags.add("needs-curation")
    # components are siblings within their container (same surgical, outlier-only flagging).
    for c in containers.values():
        if not c.components:
            continue
        cresolved, _ = reconcile_names([(comp.cid, comp.name) for comp in c.components],
                                       name_overrides)
        for comp in c.components:
            comp.name = cresolved[comp.cid]
        flagged = _mixed_convention_outliers([(comp.cid, comp.name) for comp in c.components])
        for comp in c.components:
            if comp.cid in flagged:
                comp.tags.add("needs-curation")


# --- the emission-normalized facts projection (dynamic-view plan §0.4#1) --------

def _emit_projection(facts: dict[str, Any], rules: Any) -> tuple[
        dict[str, Any], dict[str, "Container"], str, int, dict[str, str]]:
    """The one place the §0.4#1 emission-normalized facts shape is computed.

    Returns ``(facts_emitted, containers, shape, n_targets, target_to_container)``.
    ``facts_emitted`` is the curated facts with each target's ``container_id`` /
    ``container_name`` re-pointed at the EMITTED parent after the container lift (Model Y /
    a D§5 ``expand`` promotion) — the exact shape the downstream view stages bind against.
    The on-disk curated facts (and their determinism hash) are untouched: this is an
    in-memory projection only.

    The curated ``container_name`` is the AUTHORING CONTRACT for hand-owned inputs
    (scenarios.yaml steps say "Web Frontend", deployment image names bind by it) — so a
    SINGLE-member theme keeps its curated name on the emitted target (it aliases
    unambiguously). A multi-member theme's name is genuinely ambiguous at the emitted
    altitude: those targets carry the emitted container's name, and a scenario step
    addressing the theme name stays ``unresolved`` (honest; use the shape-stable
    build-target id instead — scenarios accept target ids directly).

    Factored out of :func:`run` so candidate validation (``scenario_candidates``) and
    ``arch scenarios`` share the EXACT same facts shape used by dynamic-view generation —
    no second/third mapping path (the inbox bait-and-switch this helper exists to prevent).
    """
    shape, n_targets = decide_model_shape(facts, rules)
    containers = build_containers(facts, shape=shape, promote_expanded=True)
    _apply_reconciler(containers, rules.name_overrides)

    # The emitted-parent map: a target that stands alone as a container (Model Y / D§5
    # promotion) IS its own parent; everything else lifts to its curated container.
    target_to_container = {
        t["id"]: (t["id"] if t["id"] in containers else t.get("container_id", t["id"]))
        for t in facts.get("targets", [])}

    if any(target_to_container[t["id"]] != t.get("container_id", t["id"])
           for t in facts.get("targets", [])):
        theme_size = Counter(t.get("container_id", t["id"]) for t in facts.get("targets", []))
        adjusted = []
        for t in facts.get("targets", []):
            pid = target_to_container[t["id"]]
            cur_cid = t.get("container_id", t["id"])
            if pid != cur_cid:
                t = dict(t)
                t["container_id"] = pid
                if theme_size[cur_cid] != 1:
                    t["container_name"] = containers[pid].name
            adjusted.append(t)
        facts_emitted = dict(facts)
        facts_emitted["targets"] = adjusted
    else:
        facts_emitted = facts
    return facts_emitted, containers, shape, n_targets, target_to_container


def emission_normalized_facts(facts: dict[str, Any], rules: Any) -> dict[str, Any]:
    """Public §0.4#1 helper: the emission-normalized facts projection for *facts*.

    The MANDATORY single shared entry point — ``arch scenarios`` /
    ``scenario_candidates.run`` import this so candidate validation uses the same
    target→container mapping as ``generate_structurizr.run``. ``facts_emitted`` varies
    with ``model_shape`` / ``expand``, so the curated-facts shape is NOT interchangeable
    with it. Returns the SAME object as ``facts`` when no target lifts (no spurious copy)."""
    facts_emitted, *_ = _emit_projection(facts, rules)
    return facts_emitted


# --- DSL emission --------------------------------------------------------------

def _emit_container_block(lines: list[str], c: Container, slugs: SlugRegistry,
                          connected: set[str], indent: str = "") -> None:
    ident = slugs.assign(c.cid)
    tags = sorted({"Container", *c.tags})
    lines.append(f'{indent}{ident} = container {_dsl_str(c.name)} '
                 f'{_dsl_str(_container_description(c))} '
                 f'{_dsl_str(_container_technology(c))} {{')
    lines.append(f'{indent}    tags {_dsl_str(",".join(tags))}')
    # A container with NO container-level dependency edge is an evidence-based leaf (the
    # build graph showed no in-model dependency — e.g. a single-library system, or a
    # standalone template project), not a modelling slip. Exempt it from the disconnected-
    # element inspection rather than inventing an edge we have no evidence for (§5/§9.2).
    if c.cid not in connected:
        lines.append(f"{indent}    properties {{")
        lines.append(f'{indent}        "structurizr.inspection.model.element.disconnected" "ignore"')
        lines.append(f"{indent}    }}")
    for comp in c.components:   # already sorted by cid in build_containers
        comp_ident = slugs.assign(comp.cid)
        comp_tags = sorted(comp.tags)
        # Multi-line block (see emit_relationships_dsl): a single-line
        # `{ tags ... }` is rejected by the Structurizr DSL 5.x parser. A non-empty
        # description clears the `model.component.description` inspection (§9.2).
        lines.append(f'{indent}    {comp_ident} = component {_dsl_str(comp.name)} '
                     f'{_dsl_str(_component_description(comp))} {{')
        lines.append(f'{indent}        tags {_dsl_str(",".join(comp_tags))}')
        # A component WITH a component-altitude edge is part of the relationship graph
        # (D§4.3) and stays subject to the disconnected inspection; an edgeless one is a
        # decomposition leaf (namespace/class tier, or a genuinely edge-less target) —
        # exempt it rather than inventing an edge we have no evidence for (§5/§9.2).
        if comp.cid not in connected:
            lines.append(f"{indent}        properties {{")
            lines.append(f'{indent}            "structurizr.inspection.model.element.disconnected" "ignore"')
            lines.append(f"{indent}        }}")
        lines.append(f"{indent}    }}")
    lines.append(f"{indent}}}")


def emit_components_dsl(containers: dict[str, Container], slugs: SlugRegistry,
                        connected: set[str] | None = None) -> str:
    """The container/component model fragment. Containers carrying a ``group`` label
    (Model Y themes / D§5 expanded themes) are wrapped in cosmetic ``group{}`` blocks:
    ungrouped containers first (sorted by cid — byte-identical to the pre-drill-down
    ordering when no groups exist), then groups sorted by label. Groups have no
    identifier and no model identity, so slug stability is untouched (D§3.2)."""
    connected = connected or set()
    lines = [_BANNER]
    for cid in sorted(containers):
        c = containers[cid]
        if c.group:
            continue
        _emit_container_block(lines, c, slugs, connected)
    for label in sorted({c.group for c in containers.values() if c.group}):
        lines.append(f'group {_dsl_str(label)} {{')
        for cid in sorted(cid for cid, c in containers.items() if c.group == label):
            _emit_container_block(lines, containers[cid], slugs, connected, indent="    ")
        lines.append("}")
    return "\n".join(lines) + "\n"


def emit_relationships_dsl(edges: dict, slugs: SlugRegistry,
                           component_edges: dict | None = None) -> str:
    """Container edges, then component-altitude edges (D§4), one machine-owned fragment.

    ``!impliedRelationships false`` pins the implied-relationship strategy OFF: both edge
    altitudes are emitted explicitly and deterministically, with curated labels/tags —
    the DSL default strategy would mint noisy half-duplicates (``A -> b1`` / ``a1 -> B``)
    next to them (the D§12.1 spike). Living in this overwritten-every-run fragment, the
    pin reaches existing hand-owned workspaces without a scaffold migration.
    """
    lines = [_BANNER]
    lines.append("!impliedRelationships false")
    for edge_dict in (edges, component_edges or {}):
        for (cs, ct) in sorted(edge_dict):
            e = edge_dict[(cs, ct)]
            si, ti = slugs.assign(cs), slugs.assign(ct)
            label = e.get("kind") or "Uses"
            tech = _edge_technology(e)
            tags = sorted({"Relationship", *e["tags"]})
            # Multi-line block: the Structurizr DSL parser (5.x) only accepts blocks whose
            # `{` ends the line, body on following lines, `}` on its own line — a SINGLE-line
            # `{ tags ... }` is rejected ("too many tokens"). Mirrors the container emission.
            # The technology (2nd positional) clears the `model.relationship.technology` inspection.
            lines.append(f'{si} -> {ti} {_dsl_str(label)} {_dsl_str(tech)} {{')
            lines.append(f'    tags {_dsl_str(",".join(tags))}')
            lines.append("}")
    return "\n".join(lines) + "\n"



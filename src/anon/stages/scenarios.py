def _build_lookup(facts: dict[str, Any]) -> dict[str, str]:
    """Return a mapping from every acceptable label -> container_id.

    Accepted forms for a step ``from``/``to`` value:
      - exact ``container_id``
      - exact ``container_name`` (case-sensitive, first occurrence wins)
      - build-target ``id`` (maps to its ``container_id``)
    """
    lookup: dict[str, str] = {}
    for t in facts.get("targets", []):
        cid = t.get("container_id", t["id"])
        # build-target id -> container_id
        tid = t["id"]
        if tid not in lookup:
            lookup[tid] = cid
        # container_id -> itself (idempotent)
        if cid not in lookup:
            lookup[cid] = cid
        # container_name -> container_id (first occurrence for this name wins)
        cname = t.get("container_name", "")
        if cname and cname not in lookup:
            lookup[cname] = cid
    return lookup


def _build_container_edges(facts: dict[str, Any]) -> set[tuple[str, str]]:
    """Set of (source_cid, target_cid) inter-container BUILD edges from the curated facts."""
    target_to_container: dict[str, str] = {
        t["id"]: t.get("container_id", t["id"]) for t in facts.get("targets", [])
    }
    edges: set[tuple[str, str]] = set()
    for r in facts.get("relationships", []):
        cs = target_to_container.get(r["source"])
        ct = target_to_container.get(r["target"])
        if cs and ct and cs != ct:
            edges.add((cs, ct))
    return edges


def _runtime_container_edges(
        facts: dict[str, Any]) -> tuple[set[tuple[str, str]], dict[tuple[str, str], dict[str, Any]]]:
    """Lift ``deployment.edges`` with ``kind == "calls"`` to container→container edges
    (dynamic-view plan §0.3/§3.1#1) — the RUNTIME evidence layer (Aspire ``.WithReference``).

    Returns ``(edge_set, citation_index)`` where:
      - ``edge_set`` is the set of ``(source_cid, target_cid)`` runtime ``calls`` pairs where
        BOTH endpoints resolve to a container via the SAME target→container map
        :func:`_build_lookup` uses (a build-target id mapped to its ``container_id``);
      - ``citation_index`` is keyed by ``(source_cid, target_cid)`` and supplies the
        ``description`` / ``cited_edges`` / ``weight`` a runtime-only step needs.
        Runtime-only steps have NO ``relationships[]`` entry, so ``weight`` is ``None``
        (null), NOT summed to 0 — otherwise every runtime ``ok`` step would render
        ``cited_edges:[]`` / ``weight:0``, gutting the §10.1 citation tooltip (plan §3.1#1).
        ``cited_edges`` carry the deployment edge ``detail`` strings.

    A ``deploy:image:*`` / ``infra:*`` endpoint that does NOT resolve to a build target
    yields no container; such a hop is NOT in ``edge_set`` (it is recorded as an
    out-of-model note by the candidate generator, never hidden, plan §0.3)."""
    target_to_container: dict[str, str] = {
        t["id"]: t.get("container_id", t["id"]) for t in facts.get("targets", [])
    }
    deployment = facts.get("deployment") or {}
    by_cedge: dict[tuple[str, str], list[dict[str, Any]]] = {}
    for e in deployment.get("edges", []):
        if e.get("kind") != "calls":
            continue
        cs = target_to_container.get(e.get("source"))
        ct = target_to_container.get(e.get("target"))
        # workload->workload only: both endpoints must resolve to a container, and
        # self-loops are not inter-container edges.
        if cs and ct and cs != ct:
            by_cedge.setdefault((cs, ct), []).append(e)

    edges: set[tuple[str, str]] = set()
    citations: dict[tuple[str, str], dict[str, Any]] = {}
    for cedge, deps in by_cedge.items():
        edges.add(cedge)
        details = [d for e in deps for ev in e.get("evidence", [])
                   if (d := ev.get("detail"))]
        cited = [
            {"source": e.get("source", ""), "target": e.get("target", ""),
             "evidence_layer": "runtime",
             "weight": None,
             "detail": next((ev.get("detail", "") for ev in e.get("evidence", [])), "")}
            for e in sorted(deps, key=lambda e: (e.get("source", ""), e.get("target", "")))]
        citations[cedge] = {
            # description: the first deployment-edge detail (the .WithReference(var) string),
            # a far better label than the build-graph "Uses" fall-through (plan §1a#2).
            "description": details[0] if details else "",
            "cited_edges": cited,
            "weight": None,  # runtime edges carry no relationships[] weight (plan §3.1#1)
        }
    return edges, citations


def _default_label(facts: dict[str, Any], from_cid: str, to_cid: str) -> str:
    """The first ``kind`` found among target-level edges that map to (from_cid, to_cid)."""
    target_to_container: dict[str, str] = {
        t["id"]: t.get("container_id", t["id"]) for t in facts.get("targets", [])
    }
    for r in facts.get("relationships", []):
        cs = target_to_container.get(r["source"])
        ct = target_to_container.get(r["target"])
        if cs == from_cid and ct == to_cid:
            k = r.get("kind")
            if k:
                return k
    return "Uses"



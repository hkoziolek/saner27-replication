def t_rq1(rows) -> str:
    """Corpus + RQ1 + the A1/A5 ablation columns in ONE table* (page budget): every fidelity
    number on the all-common projection; floor and propose are the autonomous rows, the curated
    model is the expression row; A1 = container edges at L0 -> all layers; A5 = edges the
    declared-never-dropped rule saves at the operating threshold 3 / at threshold 8."""
    a2a = a2_fallback(rows, pipeline_overlay(rows, pivot(rows, axis="fidelity", metric="a2a", projection="all-common"), "a2a"), "a2a")
    mojo = a2_fallback(rows, pipeline_overlay(rows, pivot(rows, axis="fidelity", metric="mojofm", projection="all-common"), "mojofm"), "mojofm")
    a5 = pivot(rows, axis="A5", metric="edges_saved")
    a1e = pivot(rows, axis="A1", metric="edges")
    meta = _meta(rows)
    targets = {}
    for r in rows:
        if r["axis"] == "RQ7" and r["technique"] == "pipeline" and r["metric"] == "targets":
            try:
                targets[r["system"]] = int(float(r["value"]))
            except (TypeError, ValueError):
                pass
    # Same first-party definition read from the workspace facts (axis=size) for systems the RQ7
    # sweep never ran (Squidex) — the column was `--` there although the facts exist.
    for r in rows:
        if (r["axis"] == "size" and r["metric"] == "first_party_targets"
                and r["system"] not in targets):
            try:
                targets[r["system"]] = int(float(r["value"]))
            except (TypeError, ValueError):
                pass
    body = []
    for s in systems_in(rows):
        m_ = meta[s]
        lang = _lang(s, m_["language"])
        a, m = a2a.get(s, {}), mojo.get(s, {})
        bl = [m.get(t) for t in ALL_COMMON if m.get(t) is not None]
        best = max(bl) if bl else None
        mark = "$^\\S$" if s in BLIND_CURATED else ""
        tgt = targets.get(s)
        l0, full = a1e.get(s, {}).get("L0"), a1e.get(s, {}).get("+L3")
        a1cell = f"{int(l0)}$\\to${int(full)}" if (l0 is not None and full is not None) else "--"
        s3, s8 = a5.get(s, {}).get("t3"), a5.get(s, {}).get("t8")
        a5cell = (f"{int(s3)}/{int(s8)}" if (s3 is not None and s8 is not None) else "--")
        body.append(f"    {_disp(s)}{mark} & {lang} & {BUILD_IDIOM.get(s, '--')} & {m_['ref_grade']} & "
                    f"{CURATION.get(s, '--')} & {m_['ref_clusters']} & {m_['ref_entities']} & "
                    f"{tgt if tgt is not None else '--'} & "
                    f"{_fmt(a.get('floor'))} & {_fmt(m.get('floor'))} & "
                    f"{_fmt(a.get('propose'))} & {_fmt(m.get('propose'))} & "
                    f"{_fmt(a.get('pipeline'))} & {_fmt(m.get('pipeline'))} & "
                    f"{_fmt(best)} & {a1cell} & {a5cell} \\\\")
    extra = ((" GT-diag = inception-era diagram, architect-reconciled (P-1 curated with that "
              "diagram in view); $^\\ddagger$anonymized "
              "proprietary system, non-replicable, corroborating only (entity count bucketed)."
              + TIER_P_A2_NOTE)
             if _p_present(rows) else "") + \
        (BLIND_NOTE if any(s in BLIND_CURATED for s in systems_in(rows)) else "")
    return (GEN + "\\begin{table*}[t]\n  \\centering\n"
            "  \\caption{Corpus, RQ1 fidelity, and the A1/A5 ablation columns (terms: "
            "\\S\\ref{sec:design}). \\#Cl./\\#Ent./\\#Tgt.\\ = reference clusters, scored "
            "entities, first-party targets; Best = best all-common classical baseline by MoJoFM; "
            "A1 = container edges at L0 $\\to$ all layers; A5 = container edges the "
            "never-drop-declared rule saves at threshold 3 / 8." + extra
            + "}\n  \\label{tab:corpus}\\label{tab:rq1}\\label{tab:rq3}\n"
            "  \\footnotesize\\setlength{\\tabcolsep}{3pt}\n"
            "  \\begin{tabular}{@{}lllll rrr rr rr rr r rr@{}}\n    \\toprule\n"
            # (a detection/expression group row was tried 2026-09-13 and cost a table* page)
            "    & & & & & & & & \\multicolumn{2}{c}{Floor} & \\multicolumn{2}{c}{Propose} & "
            "\\multicolumn{2}{c}{Curated} & Best & A1 & A5 \\\\\n"
            "    \\cmidrule(lr){9-10}\\cmidrule(lr){11-12}\\cmidrule(lr){13-14}\n"
            "    System & Lang & Build & Ref & Cur. & \\#Cl. & \\#Ent. & \\#Tgt. & a2a & MoJo & "
            "a2a & MoJo & a2a & MoJo & MoJo & edges & t3/t8 \\\\\n"
            "    \\midrule\n" + "\n".join(body) + "\n    \\bottomrule\n  \\end{tabular}\n\\end{table*}\n")


def t_rq2(rows) -> str:
    """RQ2: every technique on the all-common set, MoJoFM and a2a as two stacked blocks.
    Columns lead with the two AUTONOMOUS pipeline rows (floor, propose) so the detection
    comparison is read against them; the curated model is the expression row. ARC keeps its
    own covered subset (daggered, outside the paired test); the LLM is the rerun mean. The
    best value per row is bold whatever technique produced it (item 5.1: the win rule is in
    the caption and computed, never asserted)."""
    def block(metric):
        allc = a2_fallback(rows, pipeline_overlay(rows, pivot(rows, axis="fidelity", metric=metric, projection="all-common"), metric), metric)
        pair = pivot(rows, axis="fidelity", metric=metric, projection="pairwise")
        llmp = pivot(rows, axis="fidelity", metric=metric, projection="llm-rerun-mean")
        # rerun dispersion of the LLM baseline, printed beside its mean (review 2026-09-04)
        llms = pivot(rows, axis="fidelity", metric=f"{metric}_stdev", projection="llm-rerun-mean")
        cols = [("floor", "Floor", allc), ("propose", "Prop.", allc),
                ("pipeline", "Curated", allc), ("acdc", "ACDC", allc),
                ("arc", "ARC$^\\dagger$", pair), ("wca", "WCA", allc), ("limbo", "LIMBO", allc),
                ("dir", "dir", allc), ("cc", "cc", allc), ("llm", "LLM$^\\S$", llmp)]
        lines = []
        for s in systems_in(rows):
            vals = {}
            for key, _h, src in cols:
                v = src.get(s, {}).get(key)
                if v is None and src is allc:
                    v = pair.get(s, {}).get(key)
                vals[key] = v
            present = [v for v in vals.values() if v is not None]
            best = max(present) if present else None
            cells = []
            for key, v in vals.items():
                cell = ("\\textbf{%s}" % _fmt(v)) if (v is not None and v == best) else _fmt(v)
                sd = llms.get(s, {}).get("llm") if key == "llm" else None
                if v is not None and isinstance(sd, (int, float)):
                    cell += f"$\\pm${sd:.1f}"
                cells.append(cell)
            lines.append(f"    {_disp(s)} & " + " & ".join(cells) + " \\\\")
        header = ("    System & " + " & ".join(h for _k, h, _s in cols) + " \\\\\n")
        return cols, header, lines

    cols, head_m, body_m = block("mojofm")
    _c, head_a, body_a = block("a2a")
    win = ("Strict wins against the five all-common baselines: curated %s systems on MoJoFM "
           "and %s on a2a; floor %s and %s; propose %s and %s."
           % (_win_count(rows, "mojofm"), _win_count(rows, "a2a"),
              _win_count(rows, "mojofm", "floor"), _win_count(rows, "a2a", "floor"),
              _win_count(rows, "mojofm", "propose"), _win_count(rows, "a2a", "propose")))
    extra = ((TIER_P_NOTE + TIER_P_A2_NOTE) if _p_present(rows) else "")
    # the detection/expression group row lives in Table I only (page budget, 2026-09-13)
    groups = ""
    return (GEN + "\\begin{table*}[t]\n  \\centering\n"
            "  \\caption{RQ2: MoJoFM (top) and a2a (bottom) vs.\\ the reference on the "
            "all-common projection, best per row in bold. " + win
            + " $^\\dagger$ARC on its own covered subset. $^\\S$LLM, mean $\\pm$ sd of five "
            "reruns; -- = refused or not run." + extra
            + "}\n  \\label{tab:rq2}\n  \\footnotesize\\setlength{\\tabcolsep}{4pt}\n"
            "  \\begin{tabular}{@{}l" + "r" * len(cols) + "@{}}\n    \\toprule\n"
            + groups + head_m + "    \\midrule\n" + "\n".join(body_m)
            + "\n    \\midrule\n" + head_a.replace("System", "System (a2a)")
            + "    \\midrule\n" + "\n".join(body_a)
            + "\n    \\bottomrule\n  \\end{tabular}\n\\end{table*}\n")


def t_rq2_clusters(rows) -> str:
    """Cluster count k of every scored partition (review 2026-09-04: MoJoFM and a2a are to be
    read beside k, and Table I's #Tgt is neither the floor's k nor anyone else's) and, since
    2026-09-09 (eval plan section 12 (m)), the post-hoc adjusted Rand index of the same partitions
    as a second block set BESIDE the first in a two-column-wide float (stacked, the twelve columns
    overflow a single column by ~35pt). All-common projection; ARC falls back to its own covered
    subset (pairwise) where it has no all-common row; Ref = reference clusters. The k block has no
    LLM column (it was asked for the reference count; its per-rerun k lives in the artifact); the
    ARI block prints the LLM rerun mean +- sd. The opencv module-granularity pipeline override
    applies as in Table II. A row whose ARI cells are all absent (Tier-P: the anonymized export
    carries no ARI) is left out of the ARI block."""
    k = a2_fallback(rows, pipeline_overlay(rows, pivot(rows, axis="fidelity", metric="clusters",
                                                       projection="all-common"), "clusters"), "clusters")
    kp = pivot(rows, axis="fidelity", metric="clusters", projection="pairwise")
    ar = pipeline_overlay(rows, pivot(rows, axis="fidelity", metric="ari", projection="all-common"), "ari")
    arp = pivot(rows, axis="fidelity", metric="ari", projection="pairwise")
    arl = pivot(rows, axis="fidelity", metric="ari", projection="llm-rerun-mean")
    arls = pivot(rows, axis="fidelity", metric="ari_stdev", projection="llm-rerun-mean")
    meta = _meta(rows)
    cols = [("floor", "Floor"), ("propose", "Prop."), ("pipeline", "Cur."), ("acdc", "ACDC"),
            ("arc", "ARC$^\\dagger$"), ("wca", "WCA"), ("limbo", "LIMBO"), ("dir", "dir"),
            ("cc", "cc")]
    acols = cols + [("llm", "LLM$^\\S$")]
    body_k, body_ari = [], []
    for s in systems_in(rows):
        cells = []
        for key, _h in cols:
            v = k.get(s, {}).get(key)
            if v is None:
                v = kp.get(s, {}).get(key)
            cells.append(str(int(v)) if isinstance(v, (int, float)) else "--")
        body_k.append(f"    {_disp(s)} & {meta[s]['ref_clusters']} & " + " & ".join(cells) + " \\\\")
        vals = {}
        for key, _h in acols:
            src = arl if key == "llm" else ar
            v = src.get(s, {}).get(key)
            if v is None and key != "llm":
                v = arp.get(s, {}).get(key)
            vals[key] = v
        present = [v for v in vals.values() if v is not None]
        if not present:
            continue
        best = max(present)
        acells = []
        for key, v in vals.items():
            cell = ("\\textbf{%s}" % _fmt(v)) if (v is not None and v == best) else _fmt(v)
            sd = arls.get(s, {}).get("llm") if key == "llm" else None
            if v is not None and isinstance(sd, (int, float)):
                cell += f"$\\pm${sd:.1f}"
            acells.append(cell)
        body_ari.append(f"    {_disp(s)} & " + " & ".join(acells) + " \\\\")
    extra = ((TIER_P_NOTE + TIER_P_A2_NOTE) if _p_present(rows) else "")
    tab_k = ("  \\begin{tabular}{@{}l r" + " r" * len(cols) + "@{}}\n    \\toprule\n"
             "    System & Ref & " + " & ".join(h for _k, h in cols) + " \\\\\n    \\midrule\n"
             + "\n".join(body_k) + "\n    \\bottomrule\n  \\end{tabular}")
    tab_ari = ("  \\begin{tabular}{@{}l" + " r" * len(acols) + "@{}}\n    \\toprule\n"
               "    System & " + " & ".join(h for _k, h in acols) + " \\\\\n    \\midrule\n"
               + "\n".join(body_ari) + "\n    \\bottomrule\n  \\end{tabular}")
    return (GEN + "\\begin{table*}[t]\n  \\centering\n"
            "  \\caption{Cluster count $k$ (left; Ref = reference clusters; -- = not recorded) "
            "and post-hoc ARI ($\\times$100, right; best per row in bold; $^\\S$mean $\\pm$ sd of "
            "the LLM reruns) of every partition in Tables~\\ref{tab:rq1} and~\\ref{tab:rq2}. "
            "$^\\dagger$ARC on its own covered subset." + extra
            + "}\n  \\label{tab:rq2k}\n"
            "  \\scriptsize\\setlength{\\tabcolsep}{2.5pt}\n"
            + tab_k + "\\hfill\n" + tab_ari + "\n\\end{table*}\n")



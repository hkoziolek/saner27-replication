def build_table(name: str, rows: list[dict]) -> str:
    if name in BUILDERS:
        return BUILDERS[name](rows)
    return (GEN + f"%% '{name}' has no data yet (experiment not run) -- placeholder.\n"
            f"%% Implemented once out/** carries the {name} artifacts.\n")


PIVOT_METRICS = ("mojofm", "a2a", "ari", "nested", "clusters", "mojofm_stdev", "a2a_stdev",
                 "ari_stdev", "entities_common")


def write_fidelity_pivot(rows: list[dict], path: pathlib.Path) -> None:
    """The per-system x per-technique view the review asked for (item 5.8): one row per
    (system, technique, projection) with MoJoFM, a2a, cluster count, rerun spread (LLM) and the
    common-entity count (pairwise rows) side by side — the tidy ``results.csv`` holds the same
    numbers one per line. c2c is NOT among them: it was never scored (ARCADE's c2c exists but
    was not run), and the paper says so. Sorted, LF, byte-stable."""
    cells: dict[tuple[str, str, str], dict[str, str]] = {}
    for r in rows:
        if r["axis"] != "fidelity" or r["metric"] not in PIVOT_METRICS:
            continue
        key = (r["system"], r["technique"], r["projection"])
        cells.setdefault(key, {"language": r["language"], "granularity": r["granularity"],
                               "tier": r.get("tier", "")})[r["metric"]] = r["value"]
    header = ["system", "language", "granularity", "tier", "technique", "projection",
              *PIVOT_METRICS]
    lines = [",".join(header)]
    for (system, technique, projection), d in sorted(cells.items()):
        lines.append(",".join([system, d["language"], d["granularity"], d["tier"], technique,
                               projection, *[str(d.get(m, "")) for m in PIVOT_METRICS]]))
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    here = pathlib.Path(__file__).resolve().parent
    ap.add_argument("--results", type=pathlib.Path, default=here / "results.csv")
    ap.add_argument("--out", type=pathlib.Path, default=here.parent / "latex" / "tables")
    ap.add_argument("--only", nargs="*", choices=TABLES, help="subset to emit")
    args = ap.parse_args(argv)

    if not args.results.exists():
        print(f"no {args.results} — run aggregate_results.py first", file=sys.stderr)
        return 1
    rows = load(args.results)
    args.out.mkdir(parents=True, exist_ok=True)
    names = args.only or TABLES
    for name in names:
        (args.out / f"{name}.tex").write_text(build_table(name, rows), encoding="utf-8", newline="\n")
    if not args.only:
        write_fidelity_pivot(rows, here / "fidelity-by-system.csv")
    have = [n for n in names if n in HAVE_DATA]
    print(f"wrote {len(names)} table(s) -> {args.out}  ({len(have)} with data: {', '.join(have)})",
          file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

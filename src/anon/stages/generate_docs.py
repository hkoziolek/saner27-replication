def _salience(e: dict[str, Any], target_external: bool) -> tuple[int, list[str]]:
    """Salience = weight + seam boost (+10 interop/contract) + boundary boost (+5).
    Pure weight would walk a reader straight past a low-traffic-but-critical seam.
    Delegates to the shared :func:`salience.edge_salience` (dynamic-view plan §1a#3) so the
    guided tour and the candidate inbox compute salience identically."""
    return _salience_mod.edge_salience(e, target_external)


def build_tour(facts: dict[str, Any]) -> dict[str, Any]:
    """The deterministic entry-point → data-flow → dependents walk + the exhaustive
    critical-seams list (engine §1.1). Selection/order is a pure function of
    ``(salience, id)``; the seams list exists exactly because the walk heuristic can
    miss a critical low-weight edge (§1.7)."""
    containers, _t2c, cedges, _desc = _lift(facts)
    external = {cid for cid, c in containers.items()
                if {"external", "person"} & c.tags}
    internal = sorted(set(containers) - external)

    in_from_internal: dict[str, int] = {}
    in_from_external: dict[str, int] = {}
    out_weight: dict[str, int] = {}
    for (s, t), e in cedges.items():
        out_weight[s] = out_weight.get(s, 0) + e["weight"]
        if s in external:
            in_from_external[t] = in_from_external.get(t, 0) + e["weight"]
        else:
            in_from_internal[t] = in_from_internal.get(t, 0) + e["weight"]

    # entry points: the SHARED detector (dynamic-view plan §1a#3/§6) so the guided tour and
    # Source C's graph-walk agree on roots, then ranked by external fan-in / out-weight (the
    # place requests/data come IN). The detector folds in sdk-role / controller / executable
    # signals on top of the zero-in-degree heuristic the tour used historically.
    detected, _entry_reasons = _salience_mod.detect_entries(facts)
    entries = list(detected)
    entries.sort(key=lambda c: (-in_from_external.get(c, 0), -out_weight.get(c, 0), c))
    if not entries and internal:
        entries = sorted(internal,
                         key=lambda c: (-in_from_external.get(c, 0), c))[:1]

    walk: list[dict[str, Any]] = []
    visited: set[str] = set()
    cur = entries[0] if entries else None
    if cur:
        visited.add(cur)
    while cur is not None and len(walk) < _TOUR_MAX_HOPS:
        best: tuple[int, str] | None = None
        best_hop: dict[str, Any] | None = None
        for (s, t), e in sorted(cedges.items()):
            if s != cur or t in visited:
                continue
            sal, reasons = _salience(e, t in external)
            if best is None or (-sal, t) < (-best[0], best[1]):
                best = (sal, t)
                best_hop = {"from": s, "from_name": containers[s].name,
                            "to": t, "to_name": containers[t].name,
                            "weight": e["weight"], "kind": e.get("kind") or "uses",
                            "salience": sal, "salience_reasons": reasons}
        if best_hop is None:
            break
        walk.append(best_hop)
        cur = best_hop["to"]
        visited.add(cur)
        if cur in external:
            break  # the walk surfaced a boundary — a natural terminal

    last = walk[-1]["to"] if walk else (entries[0] if entries else None)
    dependents = sorted(s for (s, t) in cedges if t == last) if last else []

    seams = []
    for (s, t), e in sorted(cedges.items()):
        reasons = []
        if {"interop", "contract"} & e.get("tags", set()):
            reasons.append("interop/contract")
        if s in external or t in external:
            reasons.append("boundary-crossing")
        if reasons:
            seams.append({"source": s, "target": t, "weight": e["weight"],
                          "kind": e.get("kind") or "uses", "reasons": reasons})

    return {"schema": TOUR_SCHEMA, "derived_from_hash": content_hash(facts),
            "note": ("structural walk by salience (weight + seam/boundary boost); the "
                     "critical-seams list is exhaustive regardless of weight, because "
                     "the traversal heuristic alone could bury a critical edge (§1.7)"),
            "entry_points": entries, "walk": walk,
            "final_dependents": dependents, "critical_seams": seams}


def render_tour(tour: dict[str, Any]) -> str:
    lines = ["# Guided tour  (`arch datasheet --tour`)", "",
             f"> {tour['note']}", ""]
    if not tour["walk"]:
        lines += ["_No walkable edges — the model has no inter-container flow to tour._",
                  ""]
    else:
        lines.append(f"**Entry point(s):** {', '.join(tour['entry_points'])}")
        lines.append("")
        for i, hop in enumerate(tour["walk"], 1):
            why = f" — {', '.join(hop['salience_reasons'])}" \
                if hop["salience_reasons"] else ""
            lines.append(f"{i}. `{hop['from_name']}` → `{hop['to_name']}` "
                         f"(weight {hop['weight']}, {hop['kind']}, "
                         f"salience {hop['salience']}{why})")
        if tour["final_dependents"]:
            lines += ["", "**Depended on by:** "
                      + ", ".join(f"`{d}`" for d in tour["final_dependents"])]
    lines += ["", "## Critical seams (exhaustive — never buried by the walk)", ""]
    if not tour["critical_seams"]:
        lines.append("_None: no interop/contract/boundary-crossing edges in the model._")
    for s in tour["critical_seams"]:
        lines.append(f"- `{s['source']}` → `{s['target']}` (weight {s['weight']}, "
                     f"{s['kind']}): {', '.join(s['reasons'])}")
    return "\n".join(lines).rstrip() + "\n"


def run_datasheets(ws: Workspace, *,
                   facts: dict[str, Any] | None = None) -> dict[str, Any] | None:
    """The ``arch datasheet`` entry point: write ``generated/docs/datasheets.json``,
    one ``datasheets/<slug>.md`` per container, and the tour twins. Advisory,
    machine-owned, overwritten every run — never the hashed core (§9).

    Gathers the datasheets/2 side inputs (enrichment plan §7) and hands them to the
    pure :func:`build_datasheets`: the §3 risk report (echoed, staleness-guarded), the
    §6.4 git vitals (conditional on history — absence is the normal answer), the Class-V
    measurements sidecar (`arch measure`), and the hand-owned narrative overrides.

    *facts* pins the facts tier explicitly — the GUI's fast re-curate loop passes the
    freshly-written CURATED facts so newly-grouped containers get a datasheet, rather
    than the enrich-preferring default below shadowing them with a structurally stale
    enriched snapshot (the same reason ``layout.run_all_views`` takes a ``facts=``)."""
    if facts is None:
        for path in (ws.enriched_facts, ws.curated_facts, ws.extracted_facts):
            if path.exists():
                facts = load_json(path)
                break
        else:
            return None
    risk_report = load_json(ws.risk_report_json) if ws.risk_report_json.exists() else None
    measurements = load_json(ws.measurements_json) if ws.measurements_json.exists() else None
    overrides = load_yaml(ws.datasheet_overrides)
    containers, _t2c, _cedges, _desc = _lift(facts)
    vitals, vitals_reason = git_vitals(ws.repo, facts, containers)
    tests_facts = load_json(ws.extracted_facts) if ws.extracted_facts.exists() else None
    # Every facts tier currently on disk is an acceptable provenance for the risk echo:
    # `arch risk` reads the curated tier, the datasheets read the enriched one — within
    # one run those are the same model under different provenance stamps.
    accept_hashes = {content_hash(load_json(p))
                     for p in (ws.enriched_facts, ws.curated_facts, ws.extracted_facts)
                     if p.exists()}
    sheets = build_datasheets(facts, layering_rules=load_yaml(ws.layering_rules),
                              risk_report=risk_report, vitals=vitals,
                              vitals_reason=vitals_reason,
                              measurements=measurements, overrides=overrides,
                              tests_facts=tests_facts, accept_hashes=accept_hashes)
    tour = build_tour(facts)

    dump_json(sheets, ws.datasheets_json)
    ds_dir = ws.datasheets_tour_json.parent
    ds_dir.mkdir(parents=True, exist_ok=True)
    for old in ds_dir.glob("*.md"):  # machine-owned dir: drop sheets of gone containers
        old.unlink()
    slugs = SlugRegistry()
    for row in sheets["containers"]:
        (ds_dir / f"{slugs.assign(row['id'])}.md").write_text(
            render_datasheet(row), encoding="utf-8", newline="")
    dump_json(tour, ws.datasheets_tour_json)
    (ds_dir / "tour.md").write_text(render_tour(tour), encoding="utf-8", newline="")
    return {"containers": len(sheets["containers"]),
            "datasheets_json": str(ws.datasheets_json),
            "tour_hops": len(tour["walk"]),
            "critical_seams": len(tour["critical_seams"])}


def _main(argv: list[str] | None = None) -> int:  # pragma: no cover
    ap = argparse.ArgumentParser(prog="anon.stages.generate_docs",
                                 description=__doc__)
    ap.add_argument("--repo", required=True)
    ap.add_argument("--arch-dir")
    ap.add_argument("--rules-dir")
    ap.add_argument("--datasheet", action="store_true",
                    help="emit the §1 datasheets + tour (the arch datasheet path)")
    args = ap.parse_args(argv)
    ws = resolve_workspace(args.repo, args.arch_dir, args.rules_dir)
    if args.datasheet:
        result = run_datasheets(ws)
        if result is None:
            print("[datasheet] no fact model — run `arch run` first.")
            return 2
        print(f"[datasheet] {result['containers']} datasheet(s) -> "
              f"{result['datasheets_json']} (+ tour, {result['tour_hops']} hops)")
        return 0
    print("nothing to do (pass --datasheet)")
    return 2


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(_main())

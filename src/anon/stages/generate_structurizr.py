"""Stage 6 — deterministic Structurizr DSL generation (plan §9, nodes 5–6).

Aggregates curated/enriched build targets into C4 **containers** (by ``container_id``,
§7.4), lifts target->target edges to container->container edges (dropping intra-container
edges, merging parallel ones), and emits two **machine-owned** fragments that are
overwritten every run (§9):

  - ``generated/generated-components.dsl``    (container + nested component defs, tags §9.2)
  - ``generated/generated-relationships.dsl`` (container edges, with tags §9.2)

It also **scaffolds once** the hand-owned ``workspace.dsl`` and ``views.dsl`` (and never
touches them again — the three-tier lifecycle, §9.1). DSL identifiers derive from stable
ids via :class:`SlugRegistry` so ``same id -> same identifier`` and Structurizr's
layout-merge can re-attach saved positions (§9.1).

Additions over the foundation (task #4):
  - **element + relationship tagging (§9.2)** so filtered views can slice by tag.
  - the **deterministic cross-element naming reconciler (§8.3)** over each sibling set.
  - **element-budget DETECTION (advisory; §9.1/§1.1#1)**: Container view <=25, Component
    view <=20; over-budget views are detected and reported via ``over_budget_views`` (the
    run-report / CLI surface them as a warning). Enforcement (fail / auto-split) is opt-in
    at the CLI layer, not done here.

Container drill-down (plan ``2026-06-10-container-component-drilldown.md``, "D§N"):
  - **two model shapes, auto-selected** (D§2): shape **X** (container = curated theme,
    component = member build target) when the curated target count ``N`` exceeds
    ``MODEL_Y_MAX``; shape **Y** (container = build target, theme = cosmetic ``group{}``,
    component = namespace tier) when it fits. ``model_shape: x|y`` in mapping-rules pins.
  - **the component tier = build targets** (D§3, Model X): every multi-target container
    materializes one component per member target — the build graph one zoom below the
    curation grouping; the namespace tier moves to the opt-in deep path.
  - **component-altitude edges** (D§4): intra-container target->target edges (formerly
    discarded) emit as component->component; cross-container edges emit as the two
    component->container HALF-edges that Structurizr component views can actually render
    (the D§12.1 spike: ``include *`` never pulls a foreign component into a view, and the
    default implied-relationship strategy mints noisy duplicates — so both altitudes are
    explicit and the relationships fragment pins ``!impliedRelationships false``).
  - **namespace-tier interior edges** (D§4, gap-fill): the ``…/component:<ns>`` namespace->
    namespace ``symbol_use`` edges the Roslyn helper emits give a Model-Y module-container
    (and a D§5 ``expand`` promotion) its INTERIOR — without them the namespace tier rendered
    edgeless, since the target->target projection above carried only the inter-target
    altitude. Scoped to materialized components (excluded/aggregated namespaces drop their
    edges, never dangle); always intra-container, so no half-edge case arises.
  - **auto-drawn Component views** (D§7) for every container with >=1 materialized
    component; budgets stay advisory.
  - **the opt-in deep path** (D§5): an ``expand``-flagged target is promoted out of its
    theme container to a container of its own (namespaces — or classes with
    ``expand_classes`` / a ``code_view`` namespace filter — nested), the theme wrapping
    both as a cosmetic ``group{}``.
"""

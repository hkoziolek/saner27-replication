"""Machine-owned documentation + decision records for the generated model (plan §9),
plus the engine §1 per-container DATASHEETS and the guided tour (``arch datasheet``).

Structurizr's workspace inspections flag a software system that *has containers but no
documentation / no decisions* as an ERROR (``model.softwaresystem.documentation`` /
``model.softwaresystem.decisions``). Anon already knows enough — the container set,
the edge count, the coverage stratum, and *how* the model was produced — to attach an
honest, generated overview page and a baseline ADR explaining the build-graph-is-truth
invariant. Both are written into ``generated/docs`` / ``generated/adrs`` (machine-owned,
overwritten every run, never hand-edited, §9) and attached via ``!docs`` / ``!adrs`` in the
scaffolded ``workspace.dsl``.

**Datasheets (engine plan §1).** A datasheet is a cited reference-manual entry per
container — explicitly NOT an essay. The headline value is the always-available L0/L1
content: *named* fan-in/out with evidence layers, what the container owns, and its
health/coverage. The "public surface" field is CONDITIONAL on L2 and is honestly
``"L2 not extracted"`` when absent — never guessed (§1.1). The guided tour is a
deterministic structural walk by **salience** (weight + a seam boost for
``interop``/``contract``/boundary edges, §1.1) with a separate exhaustive
**critical-seams** list so a low-weight-but-critical edge is never buried by the
traversal heuristic. Honesty numbers are single-sourced (§0.4): container confidence
from :func:`confidence.container_confidence`, strata from
:func:`scorecard.element_strata`, the lift from the generator's two-step
``build_containers`` → ``build_container_edges`` — one lift, one truth.

Determinism: the content is a pure function of the facts (container names/descriptions,
counts) plus the run's commit/date carried in ``provenance``. These files are **not** part
of the byte-identical golden set (§18.4) — they document the model, they are not the model.
"""

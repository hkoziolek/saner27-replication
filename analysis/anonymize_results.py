#!/usr/bin/env python3
"""Tier-P anonymized results channel (eval plan §14.1/§14.3) — run [anonymized]-SIDE.

Walks the ``out/<system>/**`` experiment artifacts for the proprietary systems named in a
LOCAL-ONLY mapping file and emits the ONLY two artifacts allowed to cross the [anonymized] boundary:

    <export-dir>/results-anon.csv     # tidy rows, schema-compatible with analysis/results.csv
    <export-dir>/manifest-anon.json   # per-system anonymized manifest (§14.3)

Anonymization is WHITELIST-based, never blacklist (eval §14.3):

  * only numeric metric values, enumerated technique/rung/stage codes, and BUCKETED size
    fields may appear — every emitted field is validated against a per-field rule;
  * anything not matching a whitelist is DROPPED with a stderr warning (it never crosses);
  * as defense-in-depth the fully-serialized output text is scanned for forbidden tokens
    (the real system ids + the map's ``forbid`` list, case-insensitive) — a hit REFUSES the
    whole export (exit 2, nothing written), because a leak that got past the field rules is
    a bug, not a row to skip.

The mapping file is LOCAL-ONLY (never exported, never committed — it *is* the code book)::

    {
      "systems": {
        "<real-fixture-id>": {"code": "P-1", "language": "cpp", "granularity": "file",
                               "kloc": 350}
      },
      "forbid": ["ProductName", "InternalCodename"]
    }

Usage ([anonymized]-side)::

    python analysis/anonymize_results.py --map tier-p-map.json
        [--out-root out] [--refs references] [--export-dir export-anon]

STDLIB ONLY, deterministic: sorted rows, LF, no timestamps — two runs over the same tree are
byte-identical (the §15 reproducibility rule). See docs/tier-p-baseline-kit.md for the
workflow and the sign-off checklist that gates the export.
"""
from __future__ import annotations

import argparse
import csv
import io
import json
import pathlib
import re
import sys

# ------------------------------------------------------------------ whitelists (§14.3)

FIELDS = ["system", "language", "granularity", "ref_grade", "ref_clusters", "ref_entities",
          "axis", "technique", "metric", "value", "projection", "source", "tier"]

CODE_RE = re.compile(r"^P-\d{1,2}$")
LANGUAGES = {"cpp", "cs"}
GRANULARITIES = {"file", "target"}
REF_GRADES = {"GT-pub", "GT-doc", "GT-exp", "GT-diag", ""}

FIDELITY_TECHS = {"pipeline", "pipeline_4family", "acdc", "arc", "wca", "limbo", "dir", "cc"}
A2_RUNGS = {"none", "dir_leaf", "dir_top", "name", "name_segment", "edge_cc", "sdk_role",
            "module_category", "plugin_type", "propose_all", "det_curation", "hand_curation"}
# RQ3 config labels are generated by our own ablation runner (L0, +L2, t3, on/off, ...),
# never sourced from repo content — a tight charset check is the appropriate gate.
RQ3_LABEL_RE = re.compile(r"^[+A-Za-z0-9_.\-]{1,16}$")
CHURN_TECHS = {"anon", "acdc", "arc", "wca", "limbo", "dir", "cc"}
FRACTION_RE = re.compile(r"^0\.\d{1,2}$")
STAGES = {"extract", "normalize", "curate", "enrich", "generate", "drift",
          "validate-extracted", "validate-curated", "total"}
COVERAGE_LAYERS = {"L0", "L1", "L2", "L3"}
PROJECTIONS = {"pairwise", "all-common", "common-a2", "edge-vs-full", "module-gran",
               "perturb", "snapshot", "cold-warm", "n/a"}
METRICS = {"mojofm", "a2a", "clusters", "edge_f1", "edges", "edges_saved", "churn_mojofm",
           "precision", "recall", "jaccard", "wall_clock_s", "mean_confidence",
           "unmapped_targets", "abstained_targets", "edges_dropped",
           "coverage_pct_L0", "coverage_pct_L1", "coverage_pct_L2", "coverage_pct_L3",
           "identical_rate", "runs",
           # RQ7 §10 cold/warm perf (perf/rq7-perf.json). cold_s/warm_s/peak-RSS/speedup are
           # timing-class exact metrics; kloc/targets/files are the identifying SIZE signal and
           # cross exact ONLY on the §14.3 reviewer's explicit size-disclosure sign-off.
           "cold_s", "warm_s", "speedup", "cold_peak_rss_mb", "warm_peak_rss_mb",
           "kloc", "targets", "files", "cold_within_budget", "warm_within_budget"}
SOURCE_RE = re.compile(r"^[a-z0-9\-]+(/[a-z0-9\-]+)*\.(json|csv)(:[a-z0-9_\-]+)?$")

# Size buckets: entity/target counts and KLOC are the identifying scale signals (§14.3) —
# they cross only as ranges. Cluster counts stay exact (parsimony analysis needs them; the
# sign-off checklist flags them for a coarseness judgment).
SIZE_EDGES = [10, 25, 50, 100, 250, 500, 1000, 2500, 5000, 10000, 25000]
KLOC_EDGES = [10, 25, 50, 100, 250, 500, 1000, 2500]


def bucket(n, edges) -> str:
    """Deterministic half-open range label: 100 -> '100-250', 7 -> '<10', huge -> '>=25000'."""
    n = float(n)
    if n < edges[0]:
        return f"<{edges[0]}"
    for lo, hi in zip(edges, edges[1:]):
        if lo <= n < hi:
            return f"{lo}-{hi}"
    return f">={edges[-1]}"


# ------------------------------------------------------------------ helpers

def _load(path: pathlib.Path):
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None


def _num(v):
    """Round-trip numeric or None (never a string — strings can carry repo content)."""
    if isinstance(v, bool) or not isinstance(v, (int, float)):
        return None
    return round(float(v), 4)


class Dropped:
    """Counter for whitelist drops — visible, never silent (§14.3)."""

    def __init__(self) -> None:
        self.items: list[str] = []

    def add(self, what: str) -> None:
        self.items.append(what)
        print(f"  [drop] {what}", file=sys.stderr)


# ------------------------------------------------------------------ row extraction

def rows_for_system(real_id: str, cfg: dict, out_root: pathlib.Path, refs: pathlib.Path,
                    dropped: Dropped):
    code, lang, gran = cfg["code"], cfg["language"], cfg["granularity"]
    base = out_root / real_id / "baseline"
    prov = _load(refs / real_id / "provenance.json") or {}
    grade = prov.get("grade", "")
    if grade not in REF_GRADES:
        dropped.add(f"{code}: provenance grade {grade!r} not in whitelist")
        grade = ""
    ref_clusters = _num(prov.get("clusters"))
    ref_entities = bucket(prov["entities"], SIZE_EDGES) if _num(prov.get("entities")) else ""
    meta = {"system": code, "language": lang, "granularity": gran, "ref_grade": grade,
            "ref_clusters": "" if ref_clusters is None else int(ref_clusters),
            "ref_entities": ref_entities, "tier": "P"}

    def row(axis, technique, metric, value, projection, source):
        v = _num(value)
        if v is None:
            return
        yield {**meta, "axis": axis, "technique": technique, "metric": metric,
               "value": v, "projection": projection, "source": source}

    # --- RQ1/RQ2: the fair all-common comparison ---
    comp = _load(base / f"comparison-{gran}.json") or {}
    for tech, vals in sorted((comp.get("results") or {}).items()):
        if tech not in FIDELITY_TECHS:
            dropped.add(f"{code}: comparison technique {tech!r} not in whitelist")
            continue
        for metric in ("mojofm", "a2a", "clusters"):
            yield from row("fidelity", tech, metric, vals.get(metric),
                           "all-common", f"comparison-{gran}.json")

    # --- RQ2: per-technique fidelity.json (pairwise projection) ---
    for tech in sorted(FIDELITY_TECHS - {"pipeline", "pipeline_4family"}):
        fid = _load(base / f"{tech}-{gran}" / "fidelity.json") or {}
        vr = fid.get("vs_reference") or {}
        for metric in ("mojofm", "a2a"):
            yield from row("fidelity", tech, metric, vr.get(metric),
                           "pairwise", f"{tech}-{gran}/fidelity.json")
        yield from row("fidelity", tech, "clusters", fid.get("clusters"),
                       "pairwise", f"{tech}-{gran}/fidelity.json")

    # --- RQ3-A2: curation rungs ---
    a2 = _load(base / "a2-ablation.json") or {}
    for rung, vals in sorted((a2.get("rungs") or {}).items()):
        if rung not in A2_RUNGS:
            dropped.add(f"{code}: A2 rung {rung!r} not in whitelist")
            continue
        for metric in ("mojofm", "a2a", "clusters"):
            yield from row("A2", rung, metric, vals.get(metric),
                           "common-a2", "a2-ablation.json")

    # --- RQ3 A1/A3/A4/A5: edge ablations ---
    rq3 = _load(base / "rq3-ablation.json") or {}
    for axis_key, block in sorted((rq3.get("axes") or {}).items()):
        axis = axis_key.split("_", 1)[0]
        if axis not in {"A1", "A3", "A4", "A5"}:
            dropped.add(f"{code}: rq3 axis {axis_key!r} not in whitelist")
            continue
        for label, vals in sorted(block.items()):
            if not RQ3_LABEL_RE.match(label):
                dropped.add(f"{code}: rq3 label {label!r} fails charset check")
                continue
            for src_metric, out_metric in (("f1", "edge_f1"), ("precision", "precision"),
                                           ("recall", "recall"), ("jaccard", "jaccard"),
                                           ("edges", "edges"),
                                           ("edges_saved_by_rule", "edges_saved")):
                yield from row(axis, label, out_metric, vals.get(src_metric),
                               "edge-vs-full", "rq3-ablation.json")

    # --- RQ3-A8 / RQ5: stability churn ---
    churn = _load(base / "stability-churn.json") or {}
    mode = churn.get("mode", "perturb")
    if mode not in PROJECTIONS:
        dropped.add(f"{code}: churn mode {mode!r} not in whitelist")
        mode = "perturb"
    for tech, by_frac in sorted((churn.get("techniques") or {}).items()):
        if tech not in CHURN_TECHS:
            dropped.add(f"{code}: churn technique {tech!r} not in whitelist")
            continue
        for frac, vals in sorted(by_frac.items()):
            if not FRACTION_RE.match(frac):
                dropped.add(f"{code}: churn fraction {frac!r} fails format check")
                continue
            yield from row("A8", f"{tech}@{frac}", "churn_mojofm",
                           vals.get("churn_mojofm"), mode, "stability-churn.json")

    # --- RQ5: double-run determinism (determinism.json, baselines/determinism_check.py) ---
    det = _load(base / "determinism.json") or {}
    for metric in ("identical_rate", "runs"):
        yield from row("RQ5", "pipeline", metric, det.get(metric), "n/a", "determinism.json")

    # --- RQ7 perf + coverage (run-report.json trust object, eval §14.2) ---
    report = _load(out_root / real_id / "architecture" / "generated" / "run-report.json") or {}
    for stage, secs in sorted((report.get("stages") or {}).items()):
        if stage not in STAGES:
            dropped.add(f"{code}: run-report stage {stage!r} not in whitelist")
            continue
        yield from row("perf", stage, "wall_clock_s", secs, "n/a", "run-report.json")
    trust = report.get("trust") or {}
    for layer, pct in sorted((trust.get("coverage_pct") or {}).items()):
        if layer not in COVERAGE_LAYERS:
            dropped.add(f"{code}: coverage layer {layer!r} not in whitelist")
            continue
        yield from row("coverage", "pipeline", f"coverage_pct_{layer}", pct,
                       "n/a", "run-report.json")
    for metric in ("mean_confidence", "unmapped_targets", "abstained_targets",
                   "edges_dropped"):
        yield from row("coverage", "pipeline", metric, trust.get(metric),
                       "n/a", "run-report.json")

    # --- RQ7 §10: cold/warm end-to-end perf (baselines/rq7_perf.py -> perf/rq7-perf.json).
    # Emits the axis="RQ7"/technique="pipeline" rows Table VII renders. cold/warm/peak-RSS +
    # KLOC/target size cross EXACT (not bucketed) so the Tier-P point sits on the §10 scaling
    # curve — the exact-size disclosure is the reviewer's §14.3 sign-off decision (see METRICS).
    perf = _load(out_root / real_id / "perf" / "rq7-perf.json") or {}
    if perf.get("success"):
        size = perf.get("size") or {}
        rq7 = {"cold_s": (perf.get("cold") or {}).get("wall_s"),
               "warm_s": (perf.get("warm") or {}).get("wall_s"),
               "cold_peak_rss_mb": (perf.get("cold") or {}).get("peak_rss_mb"),
               "warm_peak_rss_mb": (perf.get("warm") or {}).get("peak_rss_mb"),
               "speedup": perf.get("speedup"),
               "kloc": size.get("kloc"), "targets": size.get("targets"),
               "files": size.get("files"),
               "cold_within_budget": int(bool((perf.get("budget") or {}).get("cold_within"))),
               "warm_within_budget": int(bool((perf.get("budget") or {}).get("warm_within")))}
        for metric, value in rq7.items():
            yield from row("RQ7", "pipeline", metric, value, "cold-warm", "perf/rq7-perf.json")


def manifest_for_system(real_id: str, cfg: dict, out_root: pathlib.Path,
                        refs: pathlib.Path) -> dict:
    """The §14.3 per-system anonymized manifest entry (κ + delta COUNTS, buckets, presence)."""
    base = out_root / real_id / "baseline"
    prov = _load(refs / real_id / "provenance.json") or {}
    gran = cfg["granularity"]

    delta = _load(refs / real_id / "diagram-delta.json")
    delta_counts = None
    if isinstance(delta, dict):
        delta_counts = {}
        for key in ("added", "retired", "reassigned"):
            v = delta.get(key)
            delta_counts[key] = len(v) if isinstance(v, list) else (
                int(v) if isinstance(v, int) else 0)

    targets = None
    comp = _load(base / f"comparison-{gran}.json") or {}
    a2 = _load(base / "a2-ablation.json") or {}
    for cand in (comp.get("shared_entities"), a2.get("shared_entities")):
        if isinstance(cand, int):
            targets = cand
            break

    present = sorted(
        [f"fidelity:{t}" for t in sorted(FIDELITY_TECHS)
         if (base / f"{t}-{gran}" / "fidelity.json").exists()]
        + [name for name, p in (
            ("comparison", base / f"comparison-{gran}.json"),
            ("a2-ablation", base / "a2-ablation.json"),
            ("rq3-ablation", base / "rq3-ablation.json"),
            ("stability-churn", base / "stability-churn.json"),
            ("determinism", base / "determinism.json"),
            ("run-report", out_root / real_id / "architecture" / "generated"
             / "run-report.json"),
        ) if p.exists()])

    grade = prov.get("grade", "")
    return {
        "code": cfg["code"],
        "language": cfg["language"],
        "granularity": gran,
        "ref_grade": grade if grade in REF_GRADES else "",
        "ref_clusters": prov.get("clusters") if isinstance(prov.get("clusters"), int) else None,
        "ref_entities_bucket": (bucket(prov["entities"], SIZE_EDGES)
                                if isinstance(prov.get("entities"), int) else None),
        "targets_bucket": bucket(targets, SIZE_EDGES) if targets is not None else None,
        "kloc_bucket": (bucket(cfg["kloc"], KLOC_EDGES)
                        if isinstance(cfg.get("kloc"), (int, float)) else None),
        "kappa": _num(prov.get("kappa")),
        "diagram_delta_counts": delta_counts,
        "artifacts_present": present,
        # Filled by the [anonymized]-internal reviewer at the §14.3 sign-off gate (role only, no name).
        "sign_off": {"approved_by_role": None, "approved_date": None},
    }


# ------------------------------------------------------------------ validation & export

def validate_rows(rows: list[dict]) -> list[str]:
    """Per-field whitelist assertion over every emitted row (§14.3). Returns violations."""
    bad = []
    for i, r in enumerate(rows):
        checks = [
            (CODE_RE.match(str(r["system"])), f"system {r['system']!r}"),
            (r["language"] in LANGUAGES, f"language {r['language']!r}"),
            (r["granularity"] in GRANULARITIES, f"granularity {r['granularity']!r}"),
            (r["ref_grade"] in REF_GRADES, f"ref_grade {r['ref_grade']!r}"),
            (r["metric"] in METRICS, f"metric {r['metric']!r}"),
            (isinstance(r["value"], (int, float)) and not isinstance(r["value"], bool),
             f"non-numeric value {r['value']!r}"),
            (r["projection"] in PROJECTIONS, f"projection {r['projection']!r}"),
            (SOURCE_RE.match(str(r["source"])), f"source {r['source']!r}"),
            (r["tier"] == "P", f"tier {r['tier']!r}"),
        ]
        for ok, what in checks:
            if not ok:
                bad.append(f"row {i}: {what}")
    return bad


def forbidden_scan(text: str, tokens: list[str]) -> list[str]:
    """Defense-in-depth: no forbidden token may appear ANYWHERE in the serialized export."""
    low = text.casefold()
    return [t for t in tokens if t.casefold() in low]


def serialize(rows: list[dict], manifest: dict) -> tuple[str, str]:
    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=FIELDS, lineterminator="\n")
    w.writeheader()
    w.writerows(sorted(rows, key=lambda r: (r["axis"], r["system"], r["technique"],
                                            r["metric"], r["projection"])))
    return buf.getvalue(), json.dumps(manifest, indent=2, sort_keys=True) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    here = pathlib.Path(__file__).resolve().parent
    ap.add_argument("--map", required=True, type=pathlib.Path,
                    help="LOCAL-ONLY mapping file (real id -> P-code); never exported")
    ap.add_argument("--out-root", type=pathlib.Path, default=here.parent / "out")
    ap.add_argument("--refs", type=pathlib.Path, default=here.parent / "references")
    ap.add_argument("--export-dir", type=pathlib.Path, default=here.parent / "export-anon",
                    help="output dir holding EXACTLY what may cross the boundary")
    args = ap.parse_args(argv)

    mapping = _load(args.map)
    if not mapping or not isinstance(mapping.get("systems"), dict) or not mapping["systems"]:
        print(f"ERROR: {args.map} missing or has no 'systems' entries.", file=sys.stderr)
        return 2

    # Validate the map itself before touching any artifact.
    codes = []
    for real_id, cfg in mapping["systems"].items():
        code = str(cfg.get("code", ""))
        if not CODE_RE.match(code):
            print(f"ERROR: system {real_id!r}: code {code!r} must match P-<n>.", file=sys.stderr)
            return 2
        if cfg.get("language") not in LANGUAGES or cfg.get("granularity") not in GRANULARITIES:
            print(f"ERROR: system {real_id!r}: language must be one of {sorted(LANGUAGES)}, "
                  f"granularity one of {sorted(GRANULARITIES)}.", file=sys.stderr)
            return 2
        codes.append(code)
    if len(set(codes)) != len(codes):
        print("ERROR: duplicate P-codes in the map.", file=sys.stderr)
        return 2

    dropped = Dropped()
    rows: list[dict] = []
    manifest = {"format": "tier-p-anon/1", "systems": []}
    for real_id in sorted(mapping["systems"]):
        cfg = mapping["systems"][real_id]
        rows.extend(rows_for_system(real_id, cfg, args.out_root, args.refs, dropped))
        manifest["systems"].append(manifest_for_system(real_id, cfg, args.out_root, args.refs))
    manifest["systems"].sort(key=lambda s: s["code"])

    violations = validate_rows(rows)
    if violations:
        print("REFUSED — whitelist violations (nothing written):", file=sys.stderr)
        for v in violations:
            print(f"  {v}", file=sys.stderr)
        return 2

    csv_text, manifest_text = serialize(rows, manifest)
    tokens = list(mapping["systems"]) + [str(t) for t in (mapping.get("forbid") or [])]
    hits = forbidden_scan(csv_text + manifest_text, tokens)
    if hits:
        print(f"REFUSED — forbidden token(s) {hits} found in the serialized export "
              f"(nothing written). This is a leak-path bug or a forbid/enum collision; "
              f"inspect before exporting.", file=sys.stderr)
        return 2

    args.export_dir.mkdir(parents=True, exist_ok=True)
    csv_path = args.export_dir / "results-anon.csv"
    man_path = args.export_dir / "manifest-anon.json"
    csv_path.write_text(csv_text, encoding="utf-8", newline="")
    man_path.write_text(manifest_text, encoding="utf-8", newline="")
    print(f"wrote {len(rows)} rows for {len(codes)} systems -> {csv_path}", file=sys.stderr)
    print(f"wrote manifest -> {man_path}", file=sys.stderr)
    if dropped.items:
        print(f"{len(dropped.items)} item(s) DROPPED by whitelist (listed above) — "
              f"they did not cross.", file=sys.stderr)
    print("NEXT: §14.3 sign-off — review the export dir, fill manifest sign_off, "
          "then transfer ONLY these two files.", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

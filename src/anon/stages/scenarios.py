# dynamic-view plan §3.2: the /2 shape (SUPERSET of the file-less /1 constant) — folds in
# evidence_layer / dsl / dsl_reason / dsl_steps / order / ordering_provenance at once.
DYNAMIC_VIEW_SCHEMA = "dynamic-view/2"

# The ordering-provenance enum (plan §1a#4 / §0.4#5). The existing rules/scenarios.yaml path
# is hand-authored; candidate sources stamp their own (observed-in-test / declared-in-aspire
# / synthesized / llm-proposed). Carried into the rendered view so a promoted guess never
# renders identically to an observed flow.
DEFAULT_ORDERING_PROVENANCE = "hand-authored"

log = logging.getLogger("anon.scenarios")

_BANNER = ("// GENERATED BY ANON — DO NOT EDIT. Overwritten every run (plan §9).\n"
           "// Edit scenarios in rules/scenarios.yaml; structure lives in generated-relationships.dsl.\n")


def _dsl_str(s: str) -> str:
    """Escape a string for Structurizr DSL (mirrors generate_structurizr._dsl_str)."""
    return '"' + (s or "").replace("\\", "\\\\").replace('"', '\\"') + '"'


def derived_from_hash(facts_emitted: dict[str, Any]) -> str:
    """Provenance stamp for an emission-normalized artifact (plan §3.2/§0.4#4).

    ``content_hash(facts_emitted)`` — honest provenance of EXACTLY the emission-normalized
    facts that were validated, NOT the raw curated hash (``facts_emitted`` varies with
    ``model_shape``/``expand``). Producers stamp this; it is informational provenance only
    and is NEVER the serve ``If-Hash`` freshness comparator (that is the envelope curated
    hash, plan §9)."""
    return content_hash(facts_emitted)



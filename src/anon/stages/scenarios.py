_SLUG_RE = re.compile(r"[^a-z0-9]+")


def _scenario_slug(key: str) -> str:
    """A filesystem/URL-safe slug for the scenario key (the serve layer rejects path
    separators; ``GET /model/dynamic/<scenario>`` looks up ``<scenario>.json``)."""
    return _SLUG_RE.sub("-", (key or "").lower()).strip("-") or "scenario"


def _note_for_provenance(provenance: str) -> str:
    """The provenance-aware note (plan §0.4#5): existence is validator-checked, but call
    order is only as trustworthy as the source that produced it. Never hardcode
    'hand-authored' — a promoted Source-C guess would otherwise read as an observed flow."""
    return ("existence of every step is validator-checked against the build container graph "
            "or the runtime deployment facet; the call ORDERING is "
            f"{provenance} and is never treated as observed unless the source observed it "
            "(engine §6.9c; dynamic-view plan §1a#4)")


def build_dynamic_view(scenario: dict[str, Any], facts: dict[str, Any]) -> dict[str, Any]:
    """The §6.9(c) artifact for one scenario: the ordered step list, each step validated
    against the BUILD container graph OR the RUNTIME deployment facet and CITED to its
    contributing target/deployment edges (dynamic-view plan §3.1).

    Unlike the DSL emission (which skips invalid steps), every authored step appears
    here with a ``status`` — ``ok`` | ``unresolved`` | ``unevidenced`` — so the GUI can
    flag what the architect wrote that the evidence does not support, instead of the
    artifact silently pretending the step was never written (honest abstention, moat #5).

    Each ``ok`` step is stamped with ``evidence_layer`` (``build`` wins ties), ``dsl``
    (true iff Structurizr can draw the static relationship), and — for runtime-only steps
    — a ``dsl_reason``. A non-unique ``order`` facet (distinct from the sequential
    ``index``) lets concurrent / fan-out steps share a number (plan §2/§3.1#5); it defaults
    to the sequential position when the proposal omits it. ``ordering_provenance`` is taken
    from the scenario-level field (default ``hand-authored``) and carried into the view so
    the reader knows whether the ordering was observed / declared / synthesized / proposed.
    """
    lookup = _build_lookup(facts)
    t2c = {t["id"]: t.get("container_id", t["id"]) for t in facts.get("targets", [])}
    cname = {t.get("container_id", t["id"]): t.get("container_name", t.get("name", ""))
             for t in facts.get("targets", [])}
    # contributing target-level relationships per lifted BUILD container edge (for citation)
    by_cedge: dict[tuple[str, str], list[dict[str, Any]]] = {}
    for r in facts.get("relationships", []):
        cs, ct = t2c.get(r["source"]), t2c.get(r["target"])
        if cs and ct and cs != ct:
            by_cedge.setdefault((cs, ct), []).append(r)
    # the RUNTIME container-edge set + its citation index (deployment.edges kind==calls)
    runtime_edges, runtime_cite = _runtime_container_edges(facts)

    provenance = scenario.get("ordering_provenance") or DEFAULT_ORDERING_PROVENANCE

    key = scenario.get("key", "")
    scope = scenario.get("scope", "system")
    if scope == "system":
        scope_out: dict[str, Any] = {"value": "system", "status": "ok"}
    else:
        scope_cid = lookup.get(scope)
        scope_out = {"value": scope, "status": "ok", "container_id": scope_cid} \
            if scope_cid else \
            {"value": scope, "status": "unresolved",
             "reason": f"'{scope}' does not name a container or build target"}

    steps: list[dict[str, Any]] = []
    n_ok = 0
    n_dsl = 0
    for i, step in enumerate(scenario.get("steps") or [], start=1):
        from_label = str(step.get("from", ""))
        to_label = str(step.get("to", ""))
        from_cid = lookup.get(from_label)
        to_cid = lookup.get(to_label)
        # `order` is an explicit non-unique parallel facet; default to the sequential
        # position when the proposal omits it (plan §3.1#5). The schema requires an
        # integer ≥ 1, so coerce safely: accept the authored value ONLY when it is a
        # clean positive integer (a bool, a fractional float like 2.5, a non-numeric
        # string, or a value < 1 silently truncating/colliding bands all fall back to
        # the sequential index `i`, which is always ≥ 1). int(2.5)→2 must NOT collapse
        # two distinct authored bands.
        raw_order = step.get("order")
        order = i
        if raw_order is not None and not isinstance(raw_order, bool):
            if isinstance(raw_order, int) and raw_order >= 1:
                order = raw_order
            elif isinstance(raw_order, float) and raw_order.is_integer() and raw_order >= 1:
                order = int(raw_order)
        row: dict[str, Any] = {"index": i, "order": order,
                               "from_raw": from_label, "to_raw": to_label}
        if from_cid is None or to_cid is None:
            missing = from_label if from_cid is None else to_label
            row["status"] = "unresolved"
            row["reason"] = f"'{missing}' does not name a container or build target"
            steps.append(row)
            continue
        row["from"] = from_cid
        row["to"] = to_cid
        row["from_name"] = cname.get(from_cid, from_cid)
        row["to_name"] = cname.get(to_cid, to_cid)
        rels = by_cedge.get((from_cid, to_cid))
        runtime = (from_cid, to_cid) in runtime_edges
        if not rels and not runtime:
            row["status"] = "unevidenced"
            row["reason"] = ("no evidenced build or runtime container edge "
                            f"{from_cid} -> {to_cid} — call order is never invented "
                            "over missing structure (§9.4 principle #3)")
            steps.append(row)
            continue
        n_ok += 1
        row["status"] = "ok"
        if rels:
            # BUILD evidence wins ties — the stronger structural layer (plan §3.1#2).
            row["evidence_layer"] = "build"
            row["dsl"] = True
            n_dsl += 1
            row["description"] = step.get("description") \
                or _default_label(facts, from_cid, to_cid)
            # schema says weight is ["integer","null"] — coerce so a future float
            # relationship weight can't trip jsonschema (compute_weight is int today).
            row["weight"] = int(sum(r.get("weight", 0) for r in rels))
            row["cited_edges"] = [
                {"source": r["source"], "target": r["target"],
                 "evidence_strength": r.get("evidence_strength", ""),
                 "evidence_layer": "build",
                 "weight": r.get("weight", 0)}
                for r in sorted(rels, key=lambda r: (r["source"], r["target"]))]
        else:
            # RUNTIME-only: ok in Anon's JSON/GUI view, but NOT DSL-emittable —
            # Structurizr `dynamic{}` can only reference a static container relationship
            # (plan §0.4#3).
            cite = runtime_cite.get((from_cid, to_cid), {})
            row["evidence_layer"] = "runtime"
            row["dsl"] = False
            row["dsl_reason"] = ("no static container relationship exists for Structurizr "
                                 "to reference (runtime-only edge, plan §0.4#3)")
            row["description"] = step.get("description") or cite.get("description") \
                or _default_label(facts, from_cid, to_cid)
            # runtime edges carry no relationships[] weight — null, NOT 0 (plan §3.1#1)
            row["weight"] = cite.get("weight")
            row["cited_edges"] = cite.get("cited_edges", [])
        steps.append(row)

    return {
        "schema": DYNAMIC_VIEW_SCHEMA,
        "scenario": key,
        "slug": _scenario_slug(key),
        "name": scenario.get("name", key),
        "scope": scope_out,
        "ordering_provenance": provenance,
        "derived_from_hash": content_hash(facts),
        "steps": steps,
        "valid_steps": n_ok,            # all status==ok (build-backed + runtime-only)
        "dsl_steps": n_dsl,             # ok AND dsl:true (emitted to Structurizr DSL)
        "flagged_steps": len(steps) - n_ok,   # unresolved + unevidenced
        "note": _note_for_provenance(provenance),
    }


def validate_dynamic_view(view: dict[str, Any]) -> None:
    """Validate a ``dynamic-view/2`` artifact INLINE against schema/dynamic-view.schema.json
    (plan §3.2) — the enrich_llm.py pattern (``find_schema`` + ``jsonschema.validate``); NOT
    wired into ``arch validate`` or the schema/CHANGELOG gate (advisory, core untouched)."""
    schema = load_json(find_schema("dynamic-view.schema.json"))
    jsonschema.validate(instance=view, schema=schema)



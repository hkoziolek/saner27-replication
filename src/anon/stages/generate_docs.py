# A Structurizr ADR is parsed by the Markdown decision importer: id from the filename's
# leading number, title from the first `#` heading, status from the `## Status` section.
_ADR_FILENAME = "0001-build-graph-is-the-source-of-structural-truth.md"


def _provenance_date(facts: dict[str, Any]) -> str:
    """A YYYY-MM-DD date for the ADR, taken from the run's provenance (never `Date.now`)."""
    gen = (facts.get("provenance", {}) or {}).get("generated_at", "")
    if isinstance(gen, str) and len(gen) >= 10 and gen[4] == "-" and gen[7] == "-":
        return gen[:10]
    return "unknown"


def _overview_md(system_name: str, containers: list[tuple[str, str]],
                 n_targets: int, n_edges: int, l0_pct: float | None) -> str:
    lines = [
        "# System overview",
        "",
        f"`{system_name}` — a C4 architecture model generated by **Anon** from the build "
        "graph, refined by source-level evidence. This page is regenerated on every run.",
        "",
        "## Containers",
        "",
        f"The model groups **{n_targets} build target(s)** into **{len(containers)} "
        f"container(s)** connected by **{n_edges} relationship(s)**.",
        "",
    ]
    for name, desc in containers:
        lines.append(f"- **{name}** — {desc}")
    lines += [
        "",
        "## How this model was produced",
        "",
        "Structure (containers and their dependencies) is extracted **deterministically** from "
        "the build graph — CMake / MSBuild / `.sln` / `.csproj` link and reference edges — then "
        "refined, never replaced, by source-level evidence (symbols, includes, interop). Names "
        "and descriptions may be enriched by a language model, but **no relationship or element "
        "is ever invented by an LLM**. See the architecture decision records for the governing "
        "invariants.",
        "",
    ]
    if l0_pct is not None:
        lines += [
            "## Coverage",
            "",
            f"Build-graph (L0) coverage of this model: **{l0_pct:.0f}%**. Findings derived below "
            "the L0 floor are downgraded to advisory rather than asserted.",
            "",
        ]
    return "\n".join(lines) + "\n"


def _adr_md(system_name: str, date: str) -> str:
    return (
        "# 1. The build graph is the source of structural truth\n"
        "\n"
        f"Date: {date}\n"
        "\n"
        "## Status\n"
        "\n"
        "Accepted\n"
        "\n"
        "## Context\n"
        "\n"
        f"This architecture model of `{system_name}` is generated, not hand-drawn. A generated "
        "model is only trustworthy if its structure is reproducible and evidence-backed rather "
        "than inferred.\n"
        "\n"
        "## Decision\n"
        "\n"
        "The build graph (CMake / MSBuild / `.sln` / `.csproj` targets and their declared "
        "link/reference dependencies) is treated as the source of structural truth. Source-level "
        "analysis (symbols, includes, interop) *refines* that structure — corroborating, "
        "weighting, and naming — but never adds a relationship that has no build or source "
        "evidence. Language-model enrichment touches names and descriptions only.\n"
        "\n"
        "## Consequences\n"
        "\n"
        "The same inputs produce a byte-identical model, so the diagram can be diffed and "
        "reviewed like code. Dependencies that exist at runtime but are invisible to the build "
        "graph (e.g. reflection, dynamic loading) are not shown unless a later evidence layer "
        "surfaces them; the coverage report makes that boundary explicit.\n"
    )


def run(ws: Workspace, facts: dict[str, Any], containers: list[tuple[str, str]],
        n_edges: int, *, l0_pct: float | None = None) -> dict[str, Any]:
    """Write the generated overview doc + baseline ADR. Always writes at least one file into
    each directory so the ``!docs`` / ``!adrs`` includes in ``workspace.dsl`` resolve."""
    system_name = ws.repo.name or "System"
    n_targets = len(facts.get("targets", []))
    ws.docs_dir.mkdir(parents=True, exist_ok=True)
    ws.adrs_dir.mkdir(parents=True, exist_ok=True)
    (ws.docs_dir / "01-overview.md").write_text(
        _overview_md(system_name, containers, n_targets, n_edges, l0_pct),
        encoding="utf-8", newline="")
    (ws.adrs_dir / _ADR_FILENAME).write_text(
        _adr_md(system_name, _provenance_date(facts)), encoding="utf-8", newline="")
    return {"docs": 1, "adrs": 1}


